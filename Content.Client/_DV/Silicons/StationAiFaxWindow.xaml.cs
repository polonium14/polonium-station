using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.DeviceNetwork;
using Content.Shared.Fax;
using Content.Shared.Labels.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Containers;
using Robust.Shared.Timing;

namespace Content.Client._DV.Silicons;

[GenerateTypedNameReferences]
public sealed partial class StationAiFaxWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;

    public event Action? BlankPressed;
    public event Action? TemplatePressed;
    public event Action? UploadPressed;
    public event Action? RefreshPressed;
    public event Action<DeviceAddress>? PeerSelected;
    public event Action<EntityUid>? OpenPressed;
    public event Action<EntityUid>? CopyPressed;
    public event Action<EntityUid>? SendPressed;
    public event Action<EntityUid>? ShredPressed;

    private readonly List<(EntityUid Document, StationAiFaxItem Item)> _items = new();
    private BaseContainer? _library;
    private int _maxDocuments;
    private bool _offCooldown;
    private bool _hasDestination;

    public StationAiFaxWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BlankButton.OnPressed += _ => BlankPressed?.Invoke();
        TemplateButton.OnPressed += _ => TemplatePressed?.Invoke();
        UploadButton.OnPressed += _ => UploadPressed?.Invoke();
        RefreshButton.OnPressed += _ => RefreshPressed?.Invoke();
        PeerSelector.OnItemSelected += args =>
        {
            if (args.Button.GetItemMetadata(args.Id) is DeviceAddress address)
                PeerSelected?.Invoke(address);
        };
    }

    public void SetLibrary(BaseContainer library, int maxDocuments)
    {
        _library = library;
        _maxDocuments = maxDocuments;
        RebuildDocuments();
    }

    public void UpdateState(FaxUiState state)
    {
        FromLabel.Text = state.DeviceName;
        _offCooldown = state.CanSendCooldown;
        _hasDestination = state.DestinationAddress != null;
        UpdateButtons();
        UpdatePeers(state);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_library == null)
            return;

        if (!MatchesLibrary(_library))
            RebuildDocuments();

        foreach (var (document, item) in _items)
        {
            item.SetName(GetDocumentName(document));
        }
    }

    private bool MatchesLibrary(BaseContainer library)
    {
        var documents = library.ContainedEntities;
        if (documents.Count != _items.Count)
            return false;

        for (var i = 0; i < _items.Count; i++)
        {
            if (_items[i].Document != documents[documents.Count - 1 - i])
                return false;
        }

        return true;
    }

    private void RebuildDocuments()
    {
        DocumentList.RemoveAllChildren();
        _items.Clear();

        if (_library == null)
            return;

        // Newest first, so a fresh fax is right at the top.
        for (var i = _library.ContainedEntities.Count - 1; i >= 0; i--)
        {
            var document = _library.ContainedEntities[i];
            var item = new StationAiFaxItem();
            item.SetName(GetDocumentName(document));
            item.OpenPressed += () => OpenPressed?.Invoke(document);
            item.CopyPressed += () => CopyPressed?.Invoke(document);
            item.SendPressed += () => SendPressed?.Invoke(document);
            item.ShredPressed += () => ShredPressed?.Invoke(document);

            DocumentList.AddChild(item);
            _items.Add((document, item));
        }

        CountLabel.Text = Loc.GetString("fax-machine-ui-document-count", ("count", _items.Count), ("max", _maxDocuments));
        EmptyLabel.Visible = _items.Count == 0;
        DocumentScroll.Visible = _items.Count != 0;
        UpdateButtons();
    }

    private void UpdateButtons()
    {
        var canCreate = _offCooldown && _items.Count < _maxDocuments;
        BlankButton.Disabled = !canCreate;
        TemplateButton.Disabled = !canCreate;
        UploadButton.Disabled = !canCreate;

        foreach (var (_, item) in _items)
        {
            item.SetEnabled(canCreate, _offCooldown && _hasDestination);
        }
    }

    private void UpdatePeers(FaxUiState state)
    {
        PeerSelector.Clear();

        if (state.AvailablePeers.Count == 0)
        {
            PeerSelector.AddItem(Loc.GetString("fax-machine-ui-no-peers"));
            PeerSelector.Disabled = true;
            return;
        }

        PeerSelector.Disabled = false;

        foreach (var (address, name) in state.AvailablePeers)
        {
            PeerSelector.AddItem(name);
            var id = PeerSelector.ItemCount - 1;
            PeerSelector.SetItemMetadata(id, address);
            if (address == state.DestinationAddress)
                PeerSelector.Select(id);
        }

        if (state.DestinationAddress == null)
            PeerSelected?.Invoke(state.AvailablePeers.First().Key);
    }

    private string GetDocumentName(EntityUid document)
    {
        if (_entMan.TryGetComponent<LabelComponent>(document, out var label) && label.CurrentLabel is { } text)
            return text;

        return _entMan.GetComponentOrNull<MetaDataComponent>(document)?.EntityName ?? string.Empty;
    }
}
