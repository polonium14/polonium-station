using Content.Client.UserInterface.Controls;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._DV.Silicons;

public readonly record struct StationAiFaxTemplate(ProtoId<LatheRecipePrototype> Recipe, string Name, string Category);

[GenerateTypedNameReferences]
public sealed partial class StationAiFaxTemplateWindow : FancyWindow
{
    public event Action<ProtoId<LatheRecipePrototype>>? TemplateSelected;

    private readonly List<Button> _buttons = new();
    private List<StationAiFaxTemplate> _templates = new();
    private bool _canCreate = true;

    public StationAiFaxTemplateWindow()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += _ => Rebuild();
    }

    /// <param name="templates">Templates sorted by category, then by name.</param>
    public void SetTemplates(List<StationAiFaxTemplate> templates)
    {
        _templates = templates;
        Rebuild();
    }

    public void SetCanCreate(bool canCreate)
    {
        _canCreate = canCreate;

        foreach (var button in _buttons)
        {
            button.Disabled = !canCreate;
        }
    }

    private void Rebuild()
    {
        TemplateList.RemoveAllChildren();
        _buttons.Clear();

        var search = SearchBar.Text.Trim();
        string? category = null;
        var empty = true;

        foreach (var template in _templates)
        {
            if (search.Length != 0 && !template.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                continue;

            empty = false;

            if (template.Category != category)
            {
                category = template.Category;
                TemplateList.AddChild(new Label { Text = category, StyleClasses = { "LabelSubText" }, Margin = new Thickness(2, 6, 0, 2) });
            }

            var button = new Button
            {
                Text = template.Name,
                ClipText = true,
                HorizontalExpand = true,
                ToolTip = template.Name,
                Disabled = !_canCreate,
            };
            _buttons.Add(button);

            var recipe = template.Recipe;
            button.OnPressed += _ =>
            {
                TemplateSelected?.Invoke(recipe);
                Close();
            };
            TemplateList.AddChild(button);
        }

        EmptyLabel.Visible = empty;
    }
}
