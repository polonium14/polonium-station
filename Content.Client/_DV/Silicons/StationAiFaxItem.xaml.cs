using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._DV.Silicons;

[GenerateTypedNameReferences]
public sealed partial class StationAiFaxItem : PanelContainer
{
    public event Action? OpenPressed;
    public event Action? CopyPressed;
    public event Action? SendPressed;
    public event Action? ShredPressed;

    private string? _source;

    public StationAiFaxItem()
    {
        RobustXamlLoader.Load(this);

        OpenButton.OnPressed += _ => OpenPressed?.Invoke();
        CopyButton.OnPressed += _ => CopyPressed?.Invoke();
        SendButton.OnPressed += _ => SendPressed?.Invoke();
        ShredButton.OnPressed += _ => ShredPressed?.Invoke();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // While asking for confirmation the button shows text in place of the icon.
        ShredIcon.Visible = !ShredButton.IsConfirming;
    }

    public void SetName(string name)
    {
        if (_source == name)
            return;

        _source = name;
        ShowName(name);
    }

    /// <summary>
    /// Shows a paper label, which is stored as escaped markup.
    /// </summary>
    public void SetLabel(string label)
    {
        if (_source == label)
            return;

        _source = label;
        ShowName(FormattedMessage.RemoveMarkupPermissive(label));
    }

    private void ShowName(string name)
    {
        DocumentName.Text = name;
        DocumentName.ToolTip = name;
    }

    public void SetEnabled(bool canCopy, bool canSend)
    {
        CopyButton.Disabled = !canCopy;
        SendButton.Disabled = !canSend;
    }
}
