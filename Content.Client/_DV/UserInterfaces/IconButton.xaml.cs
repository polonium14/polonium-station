using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._DV.UserInterfaces;

[GenerateTypedNameReferences]
public sealed partial class IconButton : Button
{
    private static readonly Color DisabledIconColor = Color.White.WithAlpha(0.35f);

    private bool _loaded;

    public Texture? Icon { get => TextureRect.Texture; set => TextureRect.Texture = value; }

    public IconButton()
    {
        RobustXamlLoader.Load(this);
        _loaded = true;
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();

        // The base constructor calls this before the XAML is loaded.
        if (_loaded)
            TextureRect.Modulate = Disabled ? DisabledIconColor : Color.White;
    }
}
