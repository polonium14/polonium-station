    private void UpdateVitals(HealthAnalyzerScanMessage scan)
    {
        if (scan.SpO2 is { } spO2)
        {
            SpO2Value.Text = $"{spO2:0}%";
            var (word, color) = spO2 >= SpO2HealthyFrom ? ("health-analyzer-scan-normal", Healthy)
                : spO2 >= SpO2Suffocating ? ("health-analyzer-scan-low", Warning)
                : ("health-analyzer-scan-suffocating", Critical);
            SetState(SpO2State, word, color);
            SpO2Bar.Mode = BarMode.Fill;
            SpO2Bar.Color = color;
            SpO2Bar.Target = (spO2 - SpO2Floor) / (100f - SpO2Floor);
            SpO2Bar.Notches.Clear();
            SpO2Bar.Notches.Add((SpO2Suffocating - SpO2Floor) / (100f - SpO2Floor));
            SpO2Bar.SafeBand = ((SpO2HealthyFrom - SpO2Floor) / (100f - SpO2Floor), (SpO2HealthyTo - SpO2Floor) / (100f - SpO2Floor));
            SpO2Trend.Direction = Trend(_spO2History, spO2, 0.5f);
        }
        else
        {
            SpO2Value.Text = Loc.GetString("health-analyzer-scan-none");
            SetState(SpO2State, null, Dim);
            SpO2Bar.Mode = BarMode.Outline;
            SpO2Trend.Direction = null;
        }

        SpO2Bar.ToolTip = Loc.GetString("health-analyzer-scan-spo2-tooltip");

        var bleeding = scan.SystemicBleeding || scan.Limbs.Values.Any(limb => limb.Bleeding);
        if (!float.IsNaN(scan.BloodLevel))
        {
            BloodValue.Text = $"{scan.BloodVolume.Int()}u";
            var low = scan.BloodLevel < scan.BloodlossThreshold;
            var (word, color) = low ? ("health-analyzer-scan-low", Critical)
                : bleeding ? ("health-analyzer-scan-bleeding", Warning)
                : ("health-analyzer-scan-normal", Healthy);
            SetState(BloodState, word, color);
            BloodState.Text = $"{scan.BloodLevel * 100:0}% · {BloodState.Text}";
            BloodBar.Mode = BarMode.Fill;
            BloodBar.Color = color;
            BloodBar.Target = scan.BloodLevel;
            BloodBar.Notches.Clear();
            if (!float.IsNaN(scan.BloodlossThreshold))
                BloodBar.Notches.Add(scan.BloodlossThreshold);
            BloodTrend.Direction = Trend(_bloodHistory, scan.BloodLevel * 100, 0.5f);
        }
        else
        {
            BloodValue.Text = Loc.GetString("health-analyzer-scan-none");
            SetState(BloodState, null, Dim);
            BloodBar.Mode = BarMode.Outline;
            BloodTrend.Direction = null;
        }

        BloodBar.ToolTip = Loc.GetString("health-analyzer-scan-blood-tooltip");

        if (!float.IsNaN(scan.Temperature))
        {
            TemperatureValue.Text = $"{scan.Temperature - Atmospherics.T0C:0.0} °C";
            var cold = scan.ColdDamageThreshold;
            var hot = scan.HeatDamageThreshold;
            var hasBand = !float.IsNaN(cold) && !float.IsNaN(hot);
            var (word, color) = hasBand && scan.Temperature < cold ? ("health-analyzer-scan-cold", Critical)
                : hasBand && scan.Temperature > hot ? ("health-analyzer-scan-hot", Critical)
                : ("health-analyzer-scan-normal", Healthy);
            SetState(TemperatureState, word, color);
            TemperatureBar.Mode = BarMode.Fill;
            TemperatureBar.Color = color;

            var from = hasBand ? cold - TemperatureMargin : scan.Temperature - TemperatureMargin;
            var to = hasBand ? hot + TemperatureMargin : scan.Temperature + TemperatureMargin;
            TemperatureBar.Target = (scan.Temperature - from) / (to - from);
            TemperatureBar.SafeBand = hasBand ? ((cold - from) / (to - from), (hot - from) / (to - from)) : null;
            TemperatureBar.ToolTip = $"{scan.Temperature:0.0} K";
        }
        else
        {
            TemperatureValue.Text = Loc.GetString("health-analyzer-scan-none");
            SetState(TemperatureState, null, Dim);
            TemperatureBar.Mode = BarMode.Outline;
        }
    }

    private static void SetState(Label label, string? word, Color color)
    {
        label.Text = word == null ? string.Empty : Loc.GetString(word);
        label.FontColorOverride = color;
    }

    /// <summary>
    /// Which way a reading has moved over the last few seconds.
    /// </summary>
    private static int? Trend(Queue<float> history, float value, float epsilon)
    {
        history.Enqueue(value);
        while (history.Count > TrendLength)
        {
            history.Dequeue();
        }

        if (history.Count < 3)
            return null;

        var change = value - history.Peek();
        return change > epsilon ? 1 : change < -epsilon ? -1 : 0;
    }

