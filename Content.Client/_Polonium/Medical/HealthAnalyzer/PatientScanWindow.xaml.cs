    private void UpdateHeader(HealthAnalyzerScanMessage scan)
    {
        var patient = _entMan.GetEntity(scan.Target!.Value);
        NameLabel.Text = _entMan.EntityExists(patient)
            ? Identity.Name(patient, _entMan)
            : Loc.GetString("health-analyzer-window-entity-unknown-text");

        var species = _entMan.TryGetComponent<HumanoidProfileComponent>(patient, out var humanoid)
            ? Loc.GetString(_proto.Index<SpeciesPrototype>(humanoid.Species).Name)
            : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        var (state, stateColor) = _entMan.TryGetComponent<MobStateComponent>(patient, out var mobState)
            ? mobState.CurrentState switch
            {
                MobState.Alive => (Loc.GetString("health-analyzer-scan-state-alive"), Healthy),
                MobState.Critical => (Loc.GetString("health-analyzer-scan-state-critical"), Warning),
                MobState.Dead => (Loc.GetString("health-analyzer-scan-state-dead"), Critical),
                _ => (Loc.GetString("health-analyzer-window-entity-unknown-text"), Dim),
            }
            : (Loc.GetString("health-analyzer-window-entity-unknown-text"), Dim);

        // Lower case inside the brackets: species names are capitalized as titles elsewhere.
        SpeciesLabel.Text = Loc.GetString("health-analyzer-scan-species", ("species", species.ToLowerInvariant()));
        StateLabel.Text = state;
        StateLabel.FontColorOverride = stateColor;
        StateLabel.FontOverride ??= _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 14);

        var active = scan.ScanActive ?? true;
        ScanLabel.Text = Loc.GetString(active ? "health-analyzer-scan-active" : "health-analyzer-scan-inactive");
        ScanLabel.FontColorOverride = active ? Calm : Dim;

        // Out of range the numbers are stale; dimming says so without hiding them.
        ReadoutBody.Modulate = active ? Color.White : Color.White.WithAlpha(0.55f);
    }

