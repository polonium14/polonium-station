    #region Chemicals

    private void UpdateChemicals(HealthAnalyzerScanMessage scan)
    {
        var blood = scan.BloodChemicals;
        var total = blood?.Volume ?? FixedPoint2.Zero;
        BloodChart.Clear();
        BloodChart.Capacity = Math.Max(30f, MathF.Ceiling(total.Float() / 10f) * 10f);
        BloodChart.Visible = total > 0;
        if (blood != null)
        {
            foreach (var (reagent, name, color) in Reagents(blood))
            {
                BloodChart.SetEntry(reagent.Reagent.Prototype,
                    reagent.Quantity.Float(),
                    color,
                    text: $"{name} {reagent.Quantity}u",
                    tooltip: $"{reagent.Quantity}u {name}");
            }
        }

        // Empty solutions are not worth a line; with nothing anywhere the whole section goes.
        var solutions = scan.Solutions.Where(solution => solution.Solution.Volume > 0).ToList();
        ChemicalsSection.Visible = total > 0 || solutions.Count > 0;

        var key = string.Join("|", solutions.Select(solution => solution.Name));
        if (key != _solutionKey)
        {
            _solutionKey = key;
            OtherSolutions.RemoveAllChildren();
            _otherCharts.Clear();
            _otherCaptions.Clear();
            foreach (var solution in solutions)
            {
                var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
                var caption = new Label { StyleClasses = { "LabelSubText" } };
                var chart = new SegmentedBarChart { MinHeight = 8, MaxHeight = 8, HorizontalExpand = true };
                chart.AddStyleClass(SegmentedBarChart.StyleClassClassicSplitBar);
                box.AddChild(caption);
                box.AddChild(chart);
                OtherSolutions.AddChild(box);
                _otherCharts[solution.Name] = chart;
                _otherCaptions[solution.Name] = caption;
            }
        }

        foreach (var solution in solutions)
        {
            if (!_otherCharts.TryGetValue(solution.Name, out var chart))
                continue;

            _otherCaptions[solution.Name].Text = $"{solution.Name} · {solution.Solution.Volume}u";
            chart.Clear();
            foreach (var (reagent, name, color) in Reagents(solution.Solution))
            {
                chart.SetEntry(reagent.Reagent.Prototype, reagent.Quantity.Float(), color, tooltip: $"{reagent.Quantity}u {name}");
            }
        }
    }

    /// <summary>
    /// The reagents of a solution worth drawing, with their names and colors.
    /// </summary>
    private IEnumerable<(ReagentQuantity Reagent, string Name, Color Color)> Reagents(Solution solution)
    {
        foreach (var reagent in solution.Contents)
        {
            if (reagent.Quantity <= 0)
                continue;

            yield return _proto.TryIndex<ReagentPrototype>(reagent.Reagent.Prototype, out var proto)
                ? (reagent, proto.LocalizedName, proto.SubstanceColor)
                : (reagent, Loc.GetString("chem-master-window-unknown-reagent-text"), Palettes.Neutral.Base);
        }
    }

