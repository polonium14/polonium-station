    #region Organs

    private void UpdateOrgans(HealthAnalyzerScanMessage scan)
    {
        var organs = scan.Organs.ToDictionary(organ => organ.Category.Id);
        var key = string.Join(",", organs.Keys.OrderBy(category => category));
        if (key != _organLayoutKey)
        {
            _organLayoutKey = key;
            BuildOrganRows(organs.Keys.ToHashSet());
        }

        foreach (var (category, cell) in _organCells)
        {
            if (organs.TryGetValue(category, out var organ))
                UpdateOrganCell(cell, organ);
        }
    }

    private void BuildOrganRows(HashSet<string> present)
    {
        OrganRows.RemoveAllChildren();
        _organCells.Clear();

        // The usual organs in a fixed order, then anything a species adds.
        var ordered = OrganLayout.Where(present.Contains)
            .Concat(present.Where(category => !OrganLayout.Contains(category)).OrderBy(category => category));

        // One full-width bar per organ, with its name and reading written inside, like the damage bar.
        foreach (var category in ordered)
        {
            var bar = new AnalyzerBar { MinHeight = 18, LeftText = OrganName(category) };
            bar.Notches.Add(HealthyOrganFraction);
            _organCells[category] = bar;
            OrganRows.AddChild(bar);
        }
    }

    private void UpdateOrganCell(AnalyzerBar bar, AnalyzerOrganData organ)
    {
        var fraction = organ.IntegrityCap > 0 ? (organ.Integrity / organ.IntegrityCap).Float() : 0f;
        var (word, color, mode) = organ.Missing ? ("health-analyzer-scan-organ-missing", Dim, BarMode.Outline)
            : organ.Dead ? ("health-analyzer-scan-organ-dead", Critical, BarMode.Hatched)
            : organ.Severity == OrganSeverity.Normal ? ("health-analyzer-scan-organ-healthy", Healthy, BarMode.Fill)
            : ("health-analyzer-scan-organ-damaged", Warning, BarMode.Fill);

        bar.Mode = mode;
        bar.Color = color;
        bar.Target = fraction;
        // A dead or missing organ already shows as such; the scar is drawn on a living one.
        bar.Lost = organ.IntegrityCap > 0 ? (organ.Scar / organ.IntegrityCap).Float() : 0f;

        var reading = new List<string> { Loc.GetString(word) };
        if (mode == BarMode.Fill)
            reading.Add($"{fraction * 100:0}%");
        if (organ.FailureStage > 0)
            reading.Add(Loc.GetString("health-analyzer-scan-organ-failure"));
        bar.RightText = string.Join(" · ", reading);

        var lines = new List<string> { OrganName(organ.Category) };
        if (mode == BarMode.Fill)
            lines.Add($"{organ.Integrity} / {organ.IntegrityCap}");
        if (organ.FailureStage > 0)
            lines.Add(Loc.GetString(organ.FailureNeedsSurgery ? "health-analyzer-scan-hint-failure-surgery" : "health-analyzer-scan-hint-failure",
                ("stage", organ.FailureStage)));
        if (organ.Scar > 0)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-scarred"));
        if (organ.Dead)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-dead-organ"));
        else if (organ.Missing)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-missing-organ"));
        else if (organ.Severity != OrganSeverity.Normal)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-damaged-organ"));

        bar.ToolTip = string.Join("\n", lines);
    }

    private string OrganName(ProtoId<OrganCategoryPrototype> category)
    {
        return OrganName(category.Id);
    }

    private string OrganName(string category)
