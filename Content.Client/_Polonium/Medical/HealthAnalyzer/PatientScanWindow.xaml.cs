    public PatientScanWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _limbButtons = new()
        {
            { TargetBodyPart.Head, HeadButton },
            { TargetBodyPart.Chest, ChestButton },
            { TargetBodyPart.LeftArm, LeftArmButton },
            { TargetBodyPart.RightArm, RightArmButton },
            { TargetBodyPart.LeftLeg, LeftLegButton },
            { TargetBodyPart.RightLeg, RightLegButton },
        };

        foreach (var (part, button) in _limbButtons)
        {
            button.MouseFilter = MouseFilterMode.Stop;
            button.OnPressed += _ => SelectLimb(part);
        }

        WholeBodyButton.OnPressed += _ => SelectLimb(null);

        // A thin grey frame around each section.
        foreach (var frame in new[] { VitalsFrame, BodyFrame, OrgansFrame, DamageFrame, ChemicalsSection })
        {
            frame.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                BorderColor = FrameColor,
                BorderThickness = new Thickness(1),
            };
        }

        // One tooltip for the whole bar: every damage group with the analyzer's icons, its types below.
        DamageChart.TooltipSupplier = _ => DamageTooltip();
        // The breakdown is the point of the bar, so it shows without the usual wait.
        DamageChart.TooltipDelay = 0f;
    }

