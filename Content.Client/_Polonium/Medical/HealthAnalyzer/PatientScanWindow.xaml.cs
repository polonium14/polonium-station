    private void SelectLimb(TargetBodyPart? part)
    {
        _selectedLimb = part;
        WholeBodyButton.Visible = part != null;
        foreach (var (limb, button) in _limbButtons)
        {
            LimbDoll.Outline(_resources, button, limb, limb == part);
        }

        if (_last != null)
            UpdateDamage(_last);
    }

    public void Populate(HealthAnalyzerScanMessage scan)
    {
        _last = scan;
        NoPatientLabel.Visible = scan.Target == null;
        Readout.Visible = scan.Target != null;
        if (scan.Target is not { } target)
        {
            _target = null;
            return;
        }

        var newPatient = _target != target;
        if (newPatient)
        {
            _target = target;
            _selectedLimb = null;
            WholeBodyButton.Visible = false;
            _spO2History.Clear();
            _bloodHistory.Clear();
            _damageHistory.Clear();
        }

        var reducedMotion = _cfg.GetCVar(CCVars.ReducedMotion);
        DamageChart.Animated = !reducedMotion;
        BloodChart.Animated = !reducedMotion;

        UpdateHeader(scan);
        UpdateVitals(scan);
        UpdateAlerts(scan);
        UpdateBody(scan);
        UpdateOrgans(scan);
        UpdateDamage(scan);
        UpdateChemicals(scan);

        if (newPatient)
        {
            foreach (var bar in new[] { SpO2Bar, BloodBar, TemperatureBar })
            {
                bar.Snap();
            }

            foreach (var bar in _organCells.Values)
            {
                bar.Snap();
            }
        }
    }

