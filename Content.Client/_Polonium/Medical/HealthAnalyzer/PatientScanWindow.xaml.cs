    private void UpdateDamage(HealthAnalyzerScanMessage scan)
    {
        var limb = _selectedLimb is { } part && scan.Limbs.TryGetValue(part, out var data) ? data : (AnalyzerLimbData?) null;
        var damage = new DamageSpecifier();
        foreach (var (type, amount) in limb?.Damage ?? scan.Damage)
        {
            damage.DamageDict[type] = amount;
        }

        var total = damage.GetTotal();
        _shownDamage = damage;
        DamageChart.Clear();
        DamageMarks.Marks.Clear();

        if (limb == null)
        {
            DamageTitle.Text = Loc.GetString("health-analyzer-scan-damage");
            var dead = scan.DeadThreshold ?? total;
            var capacity = FixedPoint2.Max(dead, total).Float();
            DamageChart.Capacity = Math.Max(capacity, 1f);
            if (scan.CritThreshold is { } crit)
                DamageMarks.Marks.Add((crit.Float() / DamageChart.Capacity, Warning));
            if (scan.DeadThreshold is { } deadAt)
                DamageMarks.Marks.Add((deadAt.Float() / DamageChart.Capacity, Critical));

            DamageValue.Text = $"{MathF.Round(total.Float()):0}";
            DamageTrend.Direction = Trend(_damageHistory, total.Float(), 0.5f);
        }
        else
        {
            DamageTitle.Text = Loc.GetString("health-analyzer-scan-damage-limb", ("limb", LimbName(_selectedLimb!.Value)));
            // Against the limb's own cap; without one, against death like the whole body.
            var max = limb.Value.IntegrityCap > 0 ? limb.Value.IntegrityCap : scan.DeadThreshold ?? total;
            DamageChart.Capacity = Math.Max(FixedPoint2.Max(max, total).Float(), 1f);
            DamageValue.Text = $"{MathF.Round(total.Float()):0} / {MathF.Round(max.Float()):0}";
            DamageTrend.Direction = null;
        }

        // Largest first. Segments are keyed by rank, not by group: when two groups swap places the slots stay put
        // and only their colors and labels change, while the widths glide to the new amounts.
        var rank = 0;
        foreach (var (group, amount) in damage.GetDamagePerGroup(_proto).OrderByDescending(entry => entry.Value))
        {
            if (amount <= 0)
                continue;

            // Grouping damage for a UI is what damage groups are still meant for.
#pragma warning disable CS0618
            var groupProto = _proto.Index<DamageGroupPrototype>(group);
#pragma warning restore CS0618
            DamageChart.SetEntry($"rank{rank++}", amount.Float(), GroupColor(group), text: $"{groupProto.LocalizedName} {MathF.Round(amount.Float()):0}");
        }
    }

    private Control? DamageTooltip()
    {
        if (_shownDamage.GetTotal() <= 0)
            return null;

        var list = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4, Margin = new Thickness(4) };
        foreach (var (group, amount) in _shownDamage.GetDamagePerGroup(_proto).OrderByDescending(entry => entry.Value))
        {
            if (amount <= 0)
                continue;

            // Grouping damage for a UI is what damage groups are still meant for.
#pragma warning disable CS0618
            var groupProto = _proto.Index<DamageGroupPrototype>(group);
#pragma warning restore CS0618

            var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = -2 };
            text.AddChild(new Label { Text = $"{groupProto.LocalizedName}: {amount}" });
            foreach (var type in groupProto.DamageTypes)
            {
                if (_shownDamage.DamageDict.GetValueOrDefault(type) is var typeAmount && typeAmount > 0)
                    text.AddChild(new Label { Text = $"· {DamageTypeName(type)}: {typeAmount}", StyleClasses = { "LabelSubText" } });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new TextureRect
            {
                Texture = GroupIcon(group),
                SetSize = new Vector2(30, 30),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Top,
            });
            row.AddChild(text);
            list.AddChild(row);
        }

        // The engine tooltip panel, for its look; its own text label is not used.
        var tooltip = new Tooltip { Tracking = true };
        tooltip.RemoveAllChildren();
        tooltip.AddChild(list);
        return tooltip;
    }

    private Texture GroupIcon(string group)
    {
        var rsi = _resources.GetResource<RSIResource>(GroupIcons).RSI;
        var state = rsi.TryGetState(group.ToLowerInvariant(), out _) ? group.ToLowerInvariant() : "unknown";
        return _entMan.System<SpriteSystem>().Frame0(new SpriteSpecifier.Rsi(GroupIcons, state));
    }

    private string DamageTypeName(string type)
    {
        return _proto.TryIndex<DamageTypePrototype>(type, out var proto) ? proto.LocalizedName : type;
    }

    private static Color GroupColor(string group)
    {
        // Darker than the threshold lines (orange for critical, red for death), so the lines stay readable on top,
        // and dark enough for the white labels.
        return group switch
        {
            "Brute" => Color.FromHex("#7a1d20"),
            "Burn" => Color.FromHex("#6e4a1c"),
            "Toxin" => Color.FromHex("#2a5c34"),
            "Airloss" => Color.FromHex("#35607c"),
            "Genetic" => Color.FromHex("#55407a"),
            _ => Color.FromHex("#454545"),
        };
    }

