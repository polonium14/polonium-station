    #region Alerts

    private void UpdateAlerts(HealthAnalyzerScanMessage scan)
    {
        var alerts = new List<(string Text, bool Critical)>();

        // The state itself goes first: everything below is why.
        if (scan.Target is { } target
            && _entMan.TryGetComponent<MobStateComponent>(_entMan.GetEntity(target), out var mobState))
        {
            if (mobState.CurrentState == MobState.Dead)
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-dead"), true));
            else if (mobState.CurrentState == MobState.Critical)
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-critical"), true));
        }

        if (scan.CirculationStopped)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-no-circulation"), true));

        foreach (var organ in scan.Organs)
        {
            if (organ.Missing && (organ.Category == Heart || organ.Category == Brain))
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-missing", ("organ", OrganName(organ.Category))), true));
        }

        if (scan.SpO2 is { } spO2 && spO2 < SpO2Suffocating)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-spo2", ("value", $"{spO2:0}")), true));

        var lungs = scan.Organs.Where(organ => organ.Category.Id.StartsWith("Lung")).ToList();
        if (lungs.Count > 0 && lungs.All(organ => organ.Dead || organ.Missing))
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-no-lungs"), true));

        foreach (var part in LimbOrder)
        {
            if (scan.Limbs.TryGetValue(part, out var limb) && limb.Bleeding)
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-bleeding", ("limb", LimbName(part))), false));
        }

        if (scan.SystemicBleeding)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-bleeding-systemic"), false));

        // An open patient left halfway through surgery: someone has to finish or close up.
        foreach (var part in LimbOrder)
        {
            if (scan.Limbs.TryGetValue(part, out var limb) && limb.UnfinishedSurgery)
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-surgery", ("limb", LimbName(part))), false));
        }

        foreach (var part in LimbOrder)
        {
            if (!scan.Limbs.TryGetValue(part, out var limb))
                continue;

            if (limb.Severity != WoundableSeverity.Healthy)
            {
                var severity = Loc.GetString($"health-analyzer-scan-severity-{limb.Severity.ToString().ToLowerInvariant()}");
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-limb", ("limb", LimbName(part)), ("severity", severity)),
                    limb.Severity >= WoundableSeverity.Critical));
            }

            if (limb.Bone == BoneSeverity.Broken)
                alerts.Add((Loc.GetString("health-analyzer-scan-alert-fracture", ("limb", LimbName(part))), false));
        }

        foreach (var organ in scan.Organs.Where(organ => organ.FailureStage > 0).OrderByDescending(organ => organ.FailureStage))
        {
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-failure", ("organ", OrganName(organ.Category)), ("stage", organ.FailureStage)),
                organ.FailureStage >= 3));
        }

        foreach (var organ in scan.Organs.Where(organ => organ.Dead))
        {
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-dead-organ", ("organ", OrganName(organ.Category))), true));
        }

        // Critical: it kills the host when it bursts, and a warning could get lost among the others.
        if (scan.XenoEmbryo)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-xeno-embryo"), true));

        if (scan.Lobotomized)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-lobotomy"), false));

        if (!float.IsNaN(scan.BloodLevel) && scan.BloodLevel < scan.BloodlossThreshold)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-blood", ("value", $"{scan.BloodLevel * 100:0}")), true));

        if (scan.Unrevivable is { } reason)
            alerts.Add((Loc.GetString("health-analyzer-scan-alert-unrevivable", ("reason", Loc.GetString(reason))), true));

        // Critical ones first, each group keeping its order above; they also win the slots when there are too many.
        alerts = alerts.OrderByDescending(alert => alert.Critical).ToList();
        var anyCritical = alerts.Any(alert => alert.Critical);
        var border = anyCritical ? Critical : Warning;
        AlertPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.Transparent,
            BorderColor = border,
            BorderThickness = new Thickness(2),
        };
        AlertTitle.FontColorOverride = border;
        AlertTitle.FontOverride ??= _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);

        // Nothing threatens the patient: no box at all.
        AlertPanel.Visible = alerts.Count > 0;
        if (alerts.Count == 0)
            return;

        var labels = new List<Label>();
        var shown = alerts.Count > AlertSlots ? AlertSlots - 1 : alerts.Count;
        for (var i = 0; i < shown; i++)
        {
            labels.Add(AlertLabel(alerts[i].Text, alerts[i].Critical));
        }

        if (alerts.Count > AlertSlots)
        {
            var more = AlertLabel(Loc.GetString("health-analyzer-scan-alert-more", ("count", alerts.Count - shown)), anyCritical);
            more.ToolTip = string.Join("\n", alerts.Skip(shown).Select(alert => alert.Text));
            labels.Add(more);
        }

        // Two columns of two, filled down the left first. Empty slots keep their line so the box keeps one height.
        AlertColumnLeft.RemoveAllChildren();
        AlertColumnRight.RemoveAllChildren();
        for (var i = 0; i < AlertSlots; i++)
        {
            var column = i < AlertSlots / 2 ? AlertColumnLeft : AlertColumnRight;
            column.AddChild(i < labels.Count ? labels[i] : new Label { Text = " " });
        }
    }

    private static Label AlertLabel(string text, bool critical)
    {
        // "!" marks what kills first, so the meaning does not rest on the color.
        return new Label
        {
            Text = (critical ? "! " : "· ") + text,
            FontColorOverride = critical ? Critical : Warning,
            ClipText = true,
            HorizontalExpand = true,
            ToolTip = text,
        };
    }

