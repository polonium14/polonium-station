    #region Body

    private void UpdateBody(HealthAnalyzerScanMessage scan)
    {
        var hasLimbs = scan.Limbs.Count > 0;
        foreach (var button in _limbButtons.Values)
        {
            button.Visible = hasLimbs;
        }

        DollView.Visible = hasLimbs;
        DollView.SetEntity(hasLimbs ? UpdateDoll(scan.Limbs) : null);

        var callouts = new List<(TargetBodyPart Part, string Severity, List<string> Tags, bool Bleeding)>();
        foreach (var part in LimbOrder)
        {
            if (!scan.Limbs.TryGetValue(part, out var limb))
                continue;

            // Bleeding comes first and gets its own bold red label below.
            var tags = new List<string>();
            if (limb.Bleeding)
            {
                tags.Add(Loc.GetString("health-analyzer-scan-tag-bleeding"));
            }

            if (limb.Bone is BoneSeverity.Broken or BoneSeverity.Cracked)
            {
                tags.Add(Loc.GetString(limb.Bone == BoneSeverity.Broken ? "health-analyzer-scan-tag-broken" : "health-analyzer-scan-tag-cracked"));
            }

            if (limb.Tourniquet)
            {
                tags.Add(Loc.GetString("health-analyzer-scan-tag-tourniquet"));
            }

            if (limb.UnfinishedSurgery)
            {
                tags.Add(Loc.GetString("health-analyzer-scan-tag-surgery"));
            }

            if (limb.Severity == WoundableSeverity.Healthy && tags.Count == 0)
                continue;

            var severity = Loc.GetString($"health-analyzer-scan-severity-{limb.Severity.ToString().ToLowerInvariant()}");
            callouts.Add((part, severity, tags, limb.Bleeding));
        }

        // Bleeding limbs go to the top of the list, so the most urgent thing is read first.
        callouts = callouts.OrderByDescending(callout => callout.Bleeding).ToList();

        var key = string.Join("|", callouts.Select(callout => $"{callout.Part}:{callout.Severity}:{string.Join(",", callout.Tags)}"));
        if (key == _calloutKey)
            return;

        _calloutKey = key;
        Callouts.RemoveAllChildren();
        if (callouts.Count == 0)
        {
            Callouts.AddChild(new Label
            {
                Text = Loc.GetString(hasLimbs ? "health-analyzer-scan-limbs-fine" : "health-analyzer-scan-no-limbs"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        foreach (var (part, severity, tags, bleeding) in callouts)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = -4 };
            row.AddChild(new Label { Text = LimbName(part), ClipText = true });
            row.AddChild(new Label { Text = severity, StyleClasses = { "LabelSubText" }, ClipText = true });

            if (tags.Count > 0)
            {
                var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, RectClipContent = true };
                for (var i = 0; i < tags.Count; i++)
                {
                    var tag = new Label { Text = i == 0 ? tags[i] : $" · {tags[i]}", StyleClasses = { "LabelSubText" } };
                    if (i == 0 && bleeding)
                    {
                        tag.FontOverride = _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
                        tag.FontColorOverride = Critical;
                    }

                    line.AddChild(tag);
                }

                row.AddChild(line);
            }

            row.ToolTip = LimbTooltip(scan.Limbs[part]);
            Callouts.AddChild(row);
        }
    }

    private string LimbTooltip(AnalyzerLimbData limb)
    {
        var lines = limb.Damage
            .Where(entry => entry.Value > 0)
            .Select(entry => $"{DamageTypeName(entry.Key)}: {entry.Value}")
            .ToList();

        if (limb.Bleeding)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-bleeding"));
        if (limb.Bone is BoneSeverity.Broken or BoneSeverity.Cracked)
            lines.Add(Loc.GetString("health-analyzer-scan-hint-fracture"));

        return string.Join("\n", lines);
    }

    private EntityUid UpdateDoll(Dictionary<TargetBodyPart, AnalyzerLimbData> limbs)
    {
        _doll ??= new LimbDoll(_entMan);
        foreach (var part in LimbOrder)
        {
            limbs.TryGetValue(part, out var limb);
            _doll.Set(part, (int) limb.Severity, limb.Bleeding);
        }

        return _doll.Entity;
    }

