using Content.Client._Polonium.UserInterface.Controls;
using Content.Shared._Shitmed.Targeting;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Polonium.Medical.Surgery;

/// <summary>
/// The surgery window in one view: the patient's doll, the surgeries of the picked part and the steps of the picked surgery.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class OperationWindow : DefaultWindow
{
    public event Action<TargetBodyPart>? OnPartPressed;

    private readonly Dictionary<TargetBodyPart, TextureButton> _parts;
    private readonly LimbDoll _doll;

    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IResourceCache _cache = default!;

    public OperationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _parts = new()
        {
            { TargetBodyPart.Head, HeadButton },
            { TargetBodyPart.Chest, ChestButton },
            { TargetBodyPart.LeftArm, LeftArmButton },
            { TargetBodyPart.RightArm, RightArmButton },
            { TargetBodyPart.LeftLeg, LeftLegButton },
            { TargetBodyPart.RightLeg, RightLegButton },
        };

        foreach (var (part, button) in _parts)
        {
            button.MouseFilter = MouseFilterMode.Stop;
            button.OnPressed += _ => OnPartPressed?.Invoke(part);
        }

        _doll = new LimbDoll(_entMan);
        DollView.SetEntity(_doll.Entity);
        OnClose += _doll.Release;
    }

    /// <summary>
    /// Marks the picked part on the doll and locks the parts the patient does not have.
    /// </summary>
    public void ShowParts(ICollection<TargetBodyPart> present, TargetBodyPart? picked, string pickedName, bool incisionOpen)
    {
        foreach (var (part, button) in _parts)
        {
            button.Disabled = !present.Contains(part);
            LimbDoll.Outline(_cache, button, part, part == picked);
            _doll.Set(part, present.Contains(part) ? 0 : null, false);
        }

        PartName.Text = pickedName;
        OpenIncision.Visible = incisionOpen;
    }
}
