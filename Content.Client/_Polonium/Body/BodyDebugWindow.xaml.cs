using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Body;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Polonium.Body;

[GenerateTypedNameReferences]
public sealed partial class BodyDebugWindow : FancyWindow
{
    private const int DefaultWoundDamage = 10;
    private const float KelvinToCelsius = 273.15f;
    private const string HeadCategory = "Head";

    /// <summary>
    /// Temperature slider range, kelvin: well past freezing and burning on both ends.
    /// </summary>
    private static readonly FixedPoint2 MinTemperature = 200;
    private static readonly FixedPoint2 MaxTemperature = 400;

    public event Action<List<(NetEntity Target, BodyDebugSlider Slider, FixedPoint2 Integrity)>>? OnApply;
    public event Action<BodyDebugAction, NetEntity>? OnAction;
    public event Action<string>? OnInsert;
    public event Action<NetEntity, string, int>? OnAddWound;
    public event Action? OnRefresh;
    public event Action<NetEntity, int>? OnSetFailureStage;

    /// <summary>
    /// Slider values not sent to the server yet. Dropped with every new state, organ entities change when one dies.
    /// </summary>
    private readonly Dictionary<(NetEntity Target, BodyDebugSlider Slider), FixedPoint2> _pending = new();

    public BodyDebugWindow()
    {
        RobustXamlLoader.Load(this);

        TabContainer.SetTabTitle(Tabs.GetChild(0), Loc.GetString("body-debug-section-organs"));
        TabContainer.SetTabTitle(Tabs.GetChild(1), Loc.GetString("body-debug-section-limbs"));

        ApplyButton.OnPressed += _ =>
            OnApply?.Invoke(_pending.Select(change => (change.Key.Target, change.Key.Slider, change.Value)).ToList());
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
    }

    public void SetState(BodyDebugEuiState state)
    {
        TargetLabel.Text = state.TargetName;

        ErrorLabel.Visible = state.Error != null;
        if (state.Error != null)
            ErrorLabel.Text = Loc.GetString(state.Error);

        _pending.Clear();
        ApplyButton.Disabled = true;

        BuildVitals(state.Body, state.Vitals);
        Fill(OrgansContainer, state.Organs.Select(BuildOrganRow));
        Fill(LimbsContainer, state.Limbs.Select(limb => BuildLimbRow(limb, state.WoundTypes)));
    }

    /// <summary>
    /// Whole-body sliders: blood, temperature and saturation, and the circulation switch.
    /// </summary>
    private void BuildVitals(NetEntity body, BodyDebugVitals vitals)
    {
        VitalsContainer.RemoveAllChildren();

        if (vitals.BloodVolume is { } blood && vitals.NormalBloodVolume > FixedPoint2.Zero)
        {
            VitalsContainer.AddChild(new Label { Text = Loc.GetString("body-debug-blood") });
            VitalsContainer.AddChild(MakeSlider(body, BodyDebugSlider.Blood, blood, vitals.NormalBloodVolume, FixedPoint2.Zero));
        }

        if (vitals.Temperature is { } kelvin)
        {
            VitalsContainer.AddChild(new Label { Text = Loc.GetString("body-debug-temperature") });
            VitalsContainer.AddChild(MakeSlider(body, BodyDebugSlider.Temperature, kelvin, MaxTemperature, MinTemperature,
                value => Loc.GetString("body-debug-temperature-value",
                    ("celsius", (value.Float() - KelvinToCelsius).ToString("0.0")), ("kelvin", value.Float().ToString("0.0")))));
        }

        if (vitals.Saturation is { } saturation)
        {
            VitalsContainer.AddChild(new Label { Text = Loc.GetString("body-debug-saturation") });
            VitalsContainer.AddChild(MakeSlider(body, BodyDebugSlider.Saturation, saturation, vitals.MaxSaturation, vitals.MinSaturation,
                value => value.Float().ToString("0.0")));
        }

        var circulation = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        if (vitals.CirculationStopped)
        {
            circulation.AddChild(new Label
            {
                Text = Loc.GetString("body-debug-circulation-stopped"),
                FontColorOverride = Color.FromHex("#FF3333"),
                HorizontalExpand = true,
            });
        }
        else
        {
            circulation.AddChild(new Control { HorizontalExpand = true });
        }

        // Only a stop the window made itself can be undone here; a dead or missing heart needs the organ fixed.
        circulation.AddChild(MakeButton(vitals.CirculationArrested ? "body-debug-circulation-restart" : "body-debug-circulation-stop",
            () => OnAction?.Invoke(BodyDebugAction.ToggleCirculation, body),
            vitals.CirculationStopped && !vitals.CirculationArrested));
        VitalsContainer.AddChild(circulation);
    }

    private static void Fill(BoxContainer container, IEnumerable<Control> rows)
    {
        container.RemoveAllChildren();
        foreach (var row in rows)
        {
            if (container.ChildCount > 0)
                container.AddChild(new Separator { StyleClasses = { "LowDivider" }, MinSize = new Vector2(0, 2) });

            container.AddChild(row);
        }
    }

    private Control BuildOrganRow(BodyDebugOrgan organ)
    {
        var row = MakeRow(organ.Name, organ.Category, out var header);

        switch (organ.Kind)
        {
            case BodyDebugOrganKind.Missing:
                header.AddChild(new Label { Text = Loc.GetString("body-debug-missing") });
                header.AddChild(MakeButton("body-debug-insert", () => OnInsert?.Invoke(organ.Category)));
                return row;

            case BodyDebugOrganKind.Dead when organ.Organ is { } dead:
                header.AddChild(new Label { Text = Loc.GetString("body-debug-dead") });
                header.AddChild(MakeButton("body-debug-revive", () => OnAction?.Invoke(BodyDebugAction.ReviveOrgan, dead)));
                header.AddChild(MakeButton("body-debug-remove", () => OnAction?.Invoke(BodyDebugAction.RemoveOrgan, dead)));
                return row;
        }

        if (organ.Organ is not { } uid || organ.Cap <= FixedPoint2.Zero)
            return row;

        // Protected organs keep the buttons, greyed out, so every row lines up and shows what is refused.
        header.AddChild(MakeButton("body-debug-kill", () => OnAction?.Invoke(BodyDebugAction.KillOrgan, uid), organ.Protected));
        header.AddChild(MakeButton("body-debug-remove", () => OnAction?.Invoke(BodyDebugAction.RemoveOrgan, uid), organ.Protected));

        row.AddChild(MakeSubText(Loc.GetString("body-debug-organ-status",
            ("severity", Loc.GetString($"body-debug-severity-{organ.Severity}")),
            ("healthyFrom", organ.HealthyFrom.ToString()))));

        if (organ.Modifiers.Count > 0)
        {
            row.AddChild(MakeSubText(Loc.GetString("body-debug-modifiers",
                ("modifiers", string.Join(", ", organ.Modifiers.Select(modifier => $"{modifier.Name} {modifier.Value}"))))));
        }

        row.AddChild(MakeSlider(uid, BodyDebugSlider.Organ, organ.Integrity, organ.Cap, organ.Floor));

        if (organ.FailureStages > 0)
        {
            var stages = new OptionButton();
            stages.AddItem(Loc.GetString("body-debug-failure-none"), 0);
            for (var stage = 1; stage <= organ.FailureStages; stage++)
            {
                stages.AddItem(Loc.GetString("body-debug-failure-stage", ("stage", stage)), stage);
            }

            stages.SelectId(organ.FailureStage);
            stages.OnItemSelected += args => OnSetFailureStage?.Invoke(uid, args.Id);

            var failureRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            failureRow.AddChild(new Label { Text = Loc.GetString("body-debug-failure") });
            failureRow.AddChild(stages);
            row.AddChild(failureRow);
        }
        return row;
    }

    private Control BuildLimbRow(BodyDebugLimb limb, List<string> woundTypes)
    {
        var row = MakeRow(limb.Name, limb.Category, out var header);

        if (limb.Limb is not { } uid)
        {
            header.AddChild(new Label { Text = Loc.GetString("body-debug-missing") });
            header.AddChild(MakeButton("body-debug-restore", () => OnInsert?.Invoke(limb.Category)));
            return row;
        }

        header.AddChild(MakeButton("body-debug-heal-wounds", () => OnAction?.Invoke(BodyDebugAction.HealLimb, uid)));
        header.AddChild(MakeButton("body-debug-stop-bleeding", () => OnAction?.Invoke(BodyDebugAction.StopBleeding, uid)));
        header.AddChild(MakeButton("body-debug-amputate", () => OnAction?.Invoke(BodyDebugAction.Amputate, uid), !limb.CanAmputate));

        row.AddChild(MakeSubText(Loc.GetString("body-debug-limb-status",
            ("severity", limb.Severity.ToString()),
            ("bleeds", limb.Bleeds.ToString()))));

        if (limb.Wounds.Count > 0)
        {
            row.AddChild(MakeSubText(Loc.GetString("body-debug-wounds",
                ("wounds", string.Join(", ", limb.Wounds.Select(wound => $"{wound.Name} {wound.Severity}"))))));
        }

        AddStateRow(row, uid, limb);

        if (limb.Cap > FixedPoint2.Zero)
            row.AddChild(MakeSlider(uid, BodyDebugSlider.Limb, limb.Integrity, limb.Cap, FixedPoint2.Zero));

        if (limb.BoneCap > FixedPoint2.Zero)
        {
            row.AddChild(MakeSubText(Loc.GetString("body-debug-bone-status",
                ("severity", limb.BoneSeverity.ToString()))));
            row.AddChild(MakeSlider(uid, BodyDebugSlider.Bone, limb.BoneIntegrity, limb.BoneCap, FixedPoint2.Zero));
        }

        if (woundTypes.Count == 0)
            return row;

        var types = new OptionButton();
        for (var i = 0; i < woundTypes.Count; i++)
        {
            types.AddItem(woundTypes[i], i);
        }

        types.OnItemSelected += args => types.SelectId(args.Id);
        var amount = new SpinBox { Value = DefaultWoundDamage, MinWidth = 90 };
        amount.IsValid = value => value > 0;

        var woundRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        woundRow.AddChild(types);
        woundRow.AddChild(amount);
        woundRow.AddChild(MakeButton("body-debug-add-wound", () => OnAddWound?.Invoke(uid, woundTypes[types.SelectedId], amount.Value)));
        row.AddChild(woundRow);
        return row;
    }

    /// <summary>
    /// What else is going on with the part, each with the button that undoes or sets it: the lobotomy (head only),
    /// the chest cavity, marks of an unfinished surgery and a tourniquet.
    /// </summary>
    private void AddStateRow(BoxContainer row, NetEntity uid, BodyDebugLimb limb)
    {
        var states = new List<string>();
        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };

        if (limb.Category == HeadCategory)
        {
            if (limb.Lobotomized)
                states.Add(Loc.GetString("body-debug-lobotomized"));

            buttons.AddChild(MakeButton(limb.Lobotomized ? "body-debug-unlobotomize" : "body-debug-lobotomize",
                () => OnAction?.Invoke(BodyDebugAction.ToggleLobotomy, uid)));
        }

        if (limb.CavityItem is { } item)
        {
            states.Add(Loc.GetString("body-debug-cavity", ("item", item)));
            buttons.AddChild(MakeButton("body-debug-cavity-eject", () => OnAction?.Invoke(BodyDebugAction.EjectCavity, uid)));
        }

        if (limb.UnfinishedSurgery)
        {
            states.Add(Loc.GetString("body-debug-unfinished-surgery"));
            buttons.AddChild(MakeButton("body-debug-reset-surgery", () => OnAction?.Invoke(BodyDebugAction.ResetSurgery, uid)));
        }

        if (limb.Tourniquet)
        {
            states.Add(Loc.GetString("body-debug-tourniquet"));
            buttons.AddChild(MakeButton("body-debug-remove-tourniquet", () => OnAction?.Invoke(BodyDebugAction.RemoveTourniquet, uid)));
        }

        if (states.Count > 0)
            row.AddChild(MakeSubText(string.Join(" · ", states)));

        if (buttons.ChildCount > 0)
            row.AddChild(buttons);
    }

    private static BoxContainer MakeRow(string name, string category, out BoxContainer header)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(header);
        header.AddChild(new Label
        {
            Text = Loc.GetString("body-debug-organ-name", ("name", name), ("category", category)),
            HorizontalExpand = true,
            ClipText = true,
        });
        return row;
    }

    private Control MakeSlider(NetEntity target, BodyDebugSlider kind, FixedPoint2 integrity, FixedPoint2 cap, FixedPoint2 floor,
        Func<FixedPoint2, string>? format = null)
    {
        format ??= value => IntegrityText(value, cap);
        var percent = new Label { Text = format(integrity), MinWidth = 90 };
        var slider = new Slider
        {
            // The server clamps to the floor anyway; the slider just does not offer values that cannot be reached.
            MinValue = floor.Float(),
            MaxValue = cap.Float(),
            HorizontalExpand = true,
        };
        slider.SetValueWithoutEvent(integrity.Float());
        slider.OnValueChanged += _ =>
        {
            // Tenths are fine enough for testing and keep the label readable.
            var value = FixedPoint2.New(MathF.Round(slider.Value * 10f) / 10f);
            percent.Text = format(value);
            if (value == integrity)
                _pending.Remove((target, kind));
            else
                _pending[(target, kind)] = value;

            ApplyButton.Disabled = _pending.Count == 0;
        };

        var sliderRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        sliderRow.AddChild(slider);
        sliderRow.AddChild(percent);
        return sliderRow;
    }

    private static string IntegrityText(FixedPoint2 value, FixedPoint2 cap)
    {
        return Loc.GetString("body-debug-integrity", ("value", value), ("cap", cap));
    }

    private static Label MakeSubText(string text)
    {
        return new Label { Text = text, StyleClasses = { "LabelSubText" }, ClipText = true };
    }

    private static Button MakeButton(string text, Action pressed, bool disabled = false)
    {
        var button = new Button { Text = Loc.GetString(text), Disabled = disabled };
        button.OnPressed += _ => pressed();
        return button;
    }
}
