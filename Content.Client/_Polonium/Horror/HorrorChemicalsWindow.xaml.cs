using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Horror;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Polonium.Horror;

/// <summary>
/// The eldritch horror's chemicals menu: one button per chemical it can pump into its host.
/// Ported from the cortical borer dispenser of Monolith Station (MPL-2.0).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class HorrorChemicalsWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<ProtoId<HorrorChemicalPrototype>>? OnInject;

    public HorrorChemicalsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(HorrorChemicalsBoundUserInterfaceState state)
    {
        StoredLabel.Text = Loc.GetString("horror-chemicals-window-stored", ("amount", state.Stored));
        NoHostLabel.Visible = !state.HasHost;

        ChemicalList.RemoveAllChildren();
        foreach (var id in state.Chemicals)
        {
            if (!_proto.TryIndex(id, out var chemical) || !_proto.TryIndex(chemical.Reagent, out ReagentPrototype? reagent))
                continue;

            var button = new Button
            {
                HorizontalExpand = true,
                StyleClasses = { "ButtonSquare" },
                Disabled = !state.HasHost || state.Stored < chemical.Cost,
                ToolTip = Loc.GetString(chemical.Description),
                Margin = new Thickness(2),
            };

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new PanelContainer
            {
                SetWidth = 7,
                VerticalExpand = true,
                PanelOverride = new StyleBoxFlat { BackgroundColor = reagent.SubstanceColor },
                Margin = new Thickness(0, 0, 6, 0),
            });

            var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            text.AddChild(new Label { Text = reagent.LocalizedName });
            text.AddChild(new Label
            {
                Text = Loc.GetString("horror-chemicals-window-cost", ("amount", chemical.Amount), ("cost", chemical.Cost)),
                StyleClasses = { "LabelSubText" },
            });
            row.AddChild(text);
            button.AddChild(row);

            var chosen = chemical.ID;
            button.OnPressed += _ => OnInject?.Invoke(chosen);
            ChemicalList.AddChild(button);
        }
    }
}
