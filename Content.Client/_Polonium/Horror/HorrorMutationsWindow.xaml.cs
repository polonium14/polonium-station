using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Horror;
using Content.Shared._Polonium.Horror.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Polonium.Horror;

/// <summary>
/// The horror's mutations menu: abilities and upgrades bought with devoured souls.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class HorrorMutationsWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entMan = default!;

    /// <summary>
    /// Prototype id and whether it's an upgrade.
    /// </summary>
    public event Action<string, bool>? OnBuy;

    public HorrorMutationsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(HorrorMutationsBoundUserInterfaceState state)
    {
        PointsLabel.Text = Loc.GetString("horror-mutations-window-points", ("points", state.Points), ("souls", state.Souls));

        AbilityList.RemoveAllChildren();
        var abilities = _proto.EnumeratePrototypes<EntityPrototype>()
            .Where(p => !p.Abstract && p.TryComp<HorrorActionComponent>(out var a, _entMan.ComponentFactory) && a.SoulPrice > 0)
            .OrderBy(p => p.Name);

        foreach (var proto in abilities)
        {
            proto.TryComp<HorrorActionComponent>(out var action, _entMan.ComponentFactory);
            var owned = state.Owned.Contains(proto.ID);
            AbilityList.AddChild(MakeRow(proto.Name, proto.Description, action!.SoulPrice, owned, state.Points, proto.ID, false));
        }

        UpgradeList.RemoveAllChildren();
        foreach (var upgrade in _proto.EnumeratePrototypes<HorrorUpgradePrototype>().OrderBy(u => Loc.GetString(u.Name)))
        {
            var owned = state.Owned.Contains(upgrade.ID);
            UpgradeList.AddChild(MakeRow(Loc.GetString(upgrade.Name), Loc.GetString(upgrade.Description),
                upgrade.SoulPrice, owned, state.Points, upgrade.ID, true));
        }
    }

    private Control MakeRow(string name, string description, int price, bool owned, int points, string id, bool upgrade)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 2) };

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        text.AddChild(new Label { Text = name, StyleClasses = { "LabelKeyText" } });
        text.AddChild(new RichTextLabel { Text = description, HorizontalExpand = true });
        row.AddChild(text);

        var button = new Button
        {
            Text = owned
                ? Loc.GetString("horror-mutations-window-owned")
                : Loc.GetString("horror-mutations-window-buy", ("price", price)),
            Disabled = owned || points < price,
            MinWidth = 110,
            VerticalAlignment = VAlignment.Center,
        };
        button.OnPressed += _ => OnBuy?.Invoke(id, upgrade);
        row.AddChild(button);
        return row;
    }
}
