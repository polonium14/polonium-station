using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.RoundEnd;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Polonium.RoundEnd;

[GenerateTypedNameReferences]
public sealed partial class AdminRoundEndTextWindow : FancyWindow
{
    private string _savedText = string.Empty;
    private bool _canEdit;
    private bool _valid = true;

    public event Action<string>? OnSave;

    public AdminRoundEndTextWindow()
    {
        RobustXamlLoader.Load(this);

        NoticeLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("admin-round-end-text-notice")));
        TextInput.Placeholder = new Rope.Leaf(Loc.GetString("admin-round-end-text-placeholder"));
        TextInput.OnTextChanged += _ => UpdatePreview();
        SaveButton.OnPressed += _ => OnSave?.Invoke(GetText());

        UpdatePreview();
    }

    public void SetState(AdminRoundEndTextEuiState state)
    {
        // Keep what the admin is typing if another admin saved in the meantime.
        if (GetText() == _savedText)
            TextInput.TextRope = new Rope.Leaf(state.Text);

        _savedText = state.Text;
        _canEdit = state.CanEdit;
        TextInput.Editable = state.CanEdit;

        StatusLabel.Text = Loc.GetString(state.CanEdit
            ? "admin-round-end-text-status-editable"
            : "admin-round-end-text-status-locked");

        RulesLabel.SetMessage(state.RulesWithText.Count == 0
            ? Loc.GetString("admin-round-end-text-rules-none")
            : Loc.GetString("admin-round-end-text-rules", ("rules", string.Join(", ", state.RulesWithText))));

        LastEditLabel.Text = state.Editor == null
            ? Loc.GetString("admin-round-end-text-never-edited")
            : Loc.GetString("admin-round-end-text-last-edit",
                ("admin", state.Editor),
                ("time", state.EditTime.ToString(@"hh\:mm\:ss")));

        UpdatePreview();
    }

    private string GetText()
    {
        return Rope.Collapse(TextInput.TextRope).Trim();
    }

    private void UpdatePreview()
    {
        var text = GetText();
        LimitLabel.Text = $"{text.Length}/{AdminRoundEndText.MaxLength}";

        _valid = AdminRoundEndText.TryValidate(text, out var error);
        if (!_valid)
            PreviewLabel.SetMessage(FormattedMessage.FromUnformatted(error!), Color.Red);
        else if (text.Length == 0)
            PreviewLabel.SetMessage(Loc.GetString("admin-round-end-text-preview-empty"), Color.Gray);
        else
            PreviewLabel.SetMarkup($"{Loc.GetString("admin-round-end-text-header")}\n{text}");

        SaveButton.Disabled = !_canEdit || !_valid || text == _savedText;
    }
}
