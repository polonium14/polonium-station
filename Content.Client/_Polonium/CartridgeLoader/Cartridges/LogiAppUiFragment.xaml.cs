using Content.Shared._Polonium.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Polonium.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class LogiAppUiFragment : BoxContainer
{
    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action? OnClearFinished;

    public LogiAppUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        ClearFinishedButton.OnPressed += _ => OnClearFinished?.Invoke();
    }

    public void UpdateState(List<LogiAppParcelEntry> parcels)
    {
        ParcelContainer.RemoveAllChildren();
        EmptyLabel.Visible = parcels.Count == 0;

        foreach (var parcel in parcels)
        {
            AddParcel(parcel);
        }
    }

    private void AddParcel(LogiAppParcelEntry parcel)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(4),
        };

        row.AddChild(new Label
        {
            Text = parcel.ArrivalTime.ToString(@"hh\:mm"),
            Margin = new Thickness(0, 0, 8, 0),
        });

        row.AddChild(new Label
        {
            Text = GetTypeName(parcel.Prototype),
            HorizontalExpand = true,
            ClipText = true,
        });

        row.AddChild(new Label
        {
            Text = Loc.GetString(GetStatusLocId(parcel.Status)),
        });

        ParcelContainer.AddChild(row);
    }

    private string GetTypeName(EntProtoId? prototype)
    {
        if (prototype is { } id && _prototype.TryIndex(id, out var entity))
            return entity.Name;

        return Loc.GetString("logiapp-unknown-parcel");
    }

    private static LocId GetStatusLocId(LogiAppParcelStatus status)
    {
        return status switch
        {
            LogiAppParcelStatus.WaitingInCargo => "logiapp-status-waiting-in-cargo",
            LogiAppParcelStatus.WithCourier => "logiapp-status-with-courier",
            LogiAppParcelStatus.PriorityExpired => "logiapp-status-priority-expired",
            LogiAppParcelStatus.Unlocked => "logiapp-status-unlocked",
            LogiAppParcelStatus.Damaged => "logiapp-status-damaged",
            LogiAppParcelStatus.Opened => "logiapp-status-opened",
            LogiAppParcelStatus.Destroyed => "logiapp-status-destroyed",
            _ => throw new ArgumentOutOfRangeException(nameof(status), status, null),
        };
    }
}
