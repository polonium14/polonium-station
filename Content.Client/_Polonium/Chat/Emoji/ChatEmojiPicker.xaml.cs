using System.Numerics;
using Content.Shared._Polonium.Chat.Emoji;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Input;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Polonium.Chat.Emoji;

[GenerateTypedNameReferences]
public sealed partial class ChatEmojiPicker : Popup
{
    [Dependency] private IInputManager _inputManager = default!;

    /// <summary>
    /// Raised after the player picks an emoji. The picker is already closed by then, unless shift was held.
    /// </summary>
    public event Action<ChatEmojiPrototype>? OnEmojiPicked;

    public ChatEmojiPicker()
    {
        RobustXamlLoader.Load(this);

        foreach (var emoji in UserInterfaceManager.GetUIController<ChatEmojiUIController>().Emojis)
        {
            var cell = new EmojiCell(emoji);
            cell.OnPressed += _ => Pick(emoji);
            cell.OnMouseEntered += _ => ShowPreview(emoji);
            Grid.AddChild(cell);

            if (PreviewEmoji.Emoji == null)
                ShowPreview(emoji);
        }
    }

    private void Pick(ChatEmojiPrototype emoji)
    {
        if (!_inputManager.IsKeyDown(Keyboard.Key.Shift))
            Close();

        OnEmojiPicked?.Invoke(emoji);
    }

    private void ShowPreview(ChatEmojiPrototype emoji)
    {
        PreviewEmoji.Emoji = emoji;
        PreviewCode.Text = ChatEmojiMarkup.Shortcode(emoji);
    }

    private sealed class EmojiCell : ContainerButton
    {
        private const float CellSize = 40;
        private const float EmojiSize = 32;

        private static readonly StyleBox NormalBox = new StyleBoxEmpty();
        private static readonly StyleBox HoverBox = new StyleBoxFlat(Color.White.WithAlpha(0.1f));

        public EmojiCell(ChatEmojiPrototype emoji)
        {
            SetSize = new Vector2(CellSize, CellSize);

            AddChild(new ChatEmojiControl
            {
                Emoji = emoji,
                SetSize = new Vector2(EmojiSize, EmojiSize),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
            });
        }

        protected override void DrawModeChanged()
        {
            base.DrawModeChanged();
            StyleBoxOverride = DrawMode == DrawModeEnum.Hover ? HoverBox : NormalBox;
        }
    }
}
