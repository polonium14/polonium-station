using Content.Client.Resources;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Breathalyzer;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Random;
using Robust.Shared.Timing;

namespace Content.Client._Polonium.Breathalyzer;

[GenerateTypedNameReferences]
public sealed partial class BreathalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IResourceCache _cache = default!;
    [Dependency] private IRobustRandom _random = default!;

    private const string DigitFont = "/Fonts/_Polonium/Sixtyfour/Sixtyfour-Regular.ttf";
    private const string TextFont = "/Fonts/_Polonium/KodeMono/KodeMono-Regular.ttf";
    private const string TextFontBold = "/Fonts/_Polonium/KodeMono/KodeMono-Bold.ttf";
    private const string EmptyValue = "-.--";
    private const float ScrambleInterval = 0.07f;

    public static readonly Color LcdColor = Color.FromHex("#9fe3ad");
    public static readonly Color LcdDimColor = Color.FromHex("#36503e");
    private static readonly Color LcdBackground = Color.FromHex("#0a110d");
    private static readonly Color LcdBorder = Color.FromHex("#26382c");
    private static readonly Color WarningColor = Color.FromHex("#e8453c");

    private readonly BreathalyzerSystem _breathalyzer;
    private readonly StyleBoxFlat _displayStyle;
    private Entity<BreathalyzerComponent>? _device;
    private float _scrambleAccumulator;

    public event Action? OnPrint;

    public BreathalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _breathalyzer = _entMan.System<BreathalyzerSystem>();

        HeaderLabel.FontOverride = _cache.GetFont(TextFont, 10);
        HeaderLabel.FontColorOverride = LcdDimColor;
        StateLabel.FontOverride = _cache.GetFont(TextFont, 10);
        ValueLabel.FontOverride = _cache.GetFont(DigitFont, 28);
        UnitLabel.FontOverride = _cache.GetFont(DigitFont, 14);
        StatusLabel.FontOverride = _cache.GetFont(TextFontBold, 14);

        _displayStyle = new StyleBoxFlat
        {
            BackgroundColor = LcdBackground,
            BorderColor = LcdBorder,
            BorderThickness = new Thickness(2),
        };
        Display.PanelOverride = _displayStyle;

        PrintButton.OnPressed += _ => OnPrint?.Invoke();
    }

    public void SetBreathalyzer(Entity<BreathalyzerComponent> device)
    {
        _device = device;
        Gauge.SetBreathalyzer(device.Comp, _breathalyzer);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_device is not { } device)
            return;

        var comp = device.Comp;
        var time = (float) _timing.RealTime.TotalSeconds;
        var dots = new string('.', (int) (time * 3f) % 4);
        PrintButton.Disabled = comp.State != BreathalyzerState.Result
                               || _timing.CurTime < comp.PrintReadyAt;

        switch (comp.State)
        {
            case BreathalyzerState.Blowing:
                var pulse = 0.55f + 0.45f * MathF.Sin(time * 6f);
                SetValue(EmptyValue, LcdColor.WithAlpha(pulse));
                SetStatus(Loc.GetString("breathalyzer-ui-status-blow") + dots, LcdColor);
                SetState("breathalyzer-ui-state-sampling");
                SetFooter(Loc.GetString("breathalyzer-ui-footer-blow"));
                SetBorder(LcdBorder);
                break;

            case BreathalyzerState.Analyzing:
                _scrambleAccumulator += args.DeltaSeconds;
                if (_scrambleAccumulator >= ScrambleInterval)
                {
                    _scrambleAccumulator = 0f;
                    SetValue($"{_random.Next(0, 4)}.{_random.Next(0, 100):00}", LcdColor.WithAlpha(0.6f));
                }

                SetStatus(Loc.GetString("breathalyzer-ui-status-analyze") + dots, LcdColor);
                SetState("breathalyzer-ui-state-analyzing");
                SetFooter(Loc.GetString("breathalyzer-ui-footer-analyze"));
                SetBorder(LcdBorder);
                break;

            case BreathalyzerState.Result when comp.LastResult is { } result:
                var level = _breathalyzer.GetLevel(comp, result);
                var color = level?.Color ?? LcdColor;
                SetValue(result.ToString("0.00"), color);
                SetStatus(level == null ? string.Empty : Loc.GetString(level.Name).ToUpperInvariant(), color);
                SetState("breathalyzer-ui-state-result");
                SetFooter(string.Empty);
                SetBorder(Color.InterpolateBetween(LcdBorder, color, 0.55f));
                break;

            default:
                SetValue(EmptyValue, LcdDimColor);
                if (comp.MouthpieceDirty)
                {
                    SetStatus(Loc.GetString("breathalyzer-ui-status-dirty"), WarningColor);
                    SetFooter(Loc.GetString("breathalyzer-ui-footer-dirty"));
                }
                else
                {
                    SetStatus(Loc.GetString("breathalyzer-ui-status-ready"), LcdColor);
                    SetFooter(Loc.GetString("breathalyzer-ui-footer-idle"));
                }

                SetState("breathalyzer-ui-state-idle");
                SetBorder(LcdBorder);
                break;
        }

        UnitLabel.FontColorOverride = ValueLabel.FontColorOverride;
    }

    private void SetValue(string text, Color color)
    {
        if (ValueLabel.Text != text)
            ValueLabel.Text = text;

        ValueLabel.FontColorOverride = color;
    }

    private void SetStatus(string text, Color color)
    {
        if (StatusLabel.Text != text)
            StatusLabel.Text = text;

        StatusLabel.FontColorOverride = color;
    }

    private void SetState(string loc)
    {
        var text = Loc.GetString(loc);
        if (StateLabel.Text != text)
            StateLabel.Text = text;

        StateLabel.FontColorOverride = LcdDimColor;
    }

    private void SetFooter(string text)
    {
        if (FooterLabel.Text != text)
            FooterLabel.Text = text;
    }

    private void SetBorder(Color color)
    {
        _displayStyle.BorderColor = color;
    }
}
