using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.TestChamber;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Polonium.TestChamber;

/// <summary>
/// Lists every <see cref="TestChamberKitPrototype"/> with a search bar, the selected kit's description and the clean up button.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TestChamberWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<string>? OnSpawnKit;
    public event Action? OnReset;

    private readonly ButtonGroup _group = new();
    private TestChamberKitPrototype? _selected;

    public TestChamberWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += _ => Populate();
        SpawnButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnSpawnKit?.Invoke(_selected.ID);
        };
        ResetButton.OnPressed += _ => OnReset?.Invoke();

        Populate();
        Select(null);
    }

    private void Populate()
    {
        KitList.RemoveAllChildren();
        var search = SearchBar.Text.Trim();

        // Permanent kits without a PR first, then PRs from the newest
        var kits = _proto.EnumeratePrototypes<TestChamberKitPrototype>()
            .Where(k => search.Length == 0
                        || k.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                        || (k.Pr?.Contains(search, StringComparison.CurrentCultureIgnoreCase) ?? false))
            .OrderBy(k => k.Pr != null)
            .ThenByDescending(k => PrNumber(k.Pr))
            .ThenBy(k => k.Name)
            .ToList();

        // A kit hidden by the search can't stay selected, or Drop kit would spawn something not on the list
        if (_selected != null && !kits.Contains(_selected))
            Select(null);

        foreach (var kit in kits)
        {
            var button = new Button
            {
                Text = kit.Pr == null ? kit.Name : $"{kit.Name} ({kit.Pr})",
                ToggleMode = true,
                Group = _group,
                Pressed = kit == _selected,
                ClipText = true,
                HorizontalExpand = true,
            };
            button.Label.HorizontalAlignment = HAlignment.Left;
            button.OnPressed += _ => Select(kit);
            KitList.AddChild(button);
        }
    }

    private void Select(TestChamberKitPrototype? kit)
    {
        _selected = kit;
        SpawnButton.Disabled = kit == null;

        if (kit == null)
        {
            DescriptionLabel.SetMarkupPermissive(Loc.GetString("test-chamber-window-pick"));
            return;
        }

        var entities = string.Join(", ", kit.Entities.Select(e =>
            _proto.TryIndex(e.Key, out var proto) ? $"{proto.Name} x{e.Value}" : $"{e.Key} x{e.Value}"));
        var contents = Loc.GetString("test-chamber-window-contents", ("entities", entities));
        DescriptionLabel.SetMarkupPermissive($"{kit.Description}\n[color=gray]{contents}[/color]");
    }

    private static int PrNumber(string? pr)
    {
        var hash = pr?.LastIndexOf('#') ?? -1;
        return hash >= 0 && int.TryParse(pr![(hash + 1)..], out var number) ? number : 0;
    }
}
