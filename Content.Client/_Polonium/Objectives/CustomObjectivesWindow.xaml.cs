using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Objectives;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Polonium.Objectives;

[GenerateTypedNameReferences]
public sealed partial class CustomObjectivesWindow : FancyWindow
{
    private const string SyndicateIssuerId = "TheSyndicate";

    private readonly List<string> _issuerIds = new();

    public event Action<string, string, string>? OnAdd;
    public event Action<NetEntity, CustomObjectiveStatus>? OnSetStatus;
    public event Action<NetEntity>? OnRemove;

    public CustomObjectivesWindow()
    {
        RobustXamlLoader.Load(this);

        TitleEdit.IsValid = text => text.Length <= CustomObjectiveLimits.MaxTitleLength;
        TitleEdit.OnTextChanged += _ => UpdateAddButton();
        DescriptionEdit.OnTextChanged += _ => UpdateAddButton();
        IssuerOptions.OnItemSelected += args => IssuerOptions.SelectId(args.Id);
        AddButton.OnPressed += _ => Add();

        UpdateAddButton();
    }

    public void SetState(CustomObjectivesEuiState state)
    {
        PlayerLabel.Text = Loc.GetString("custom-objectives-player", ("player", state.PlayerName));
        NoMindLabel.Visible = !state.HasMind;
        AddButton.Disabled = !state.HasMind;
        EmptyLabel.Visible = state.HasMind && state.Objectives.Count == 0;

        SetIssuers(state.Issuers);

        ObjectivesContainer.RemoveAllChildren();
        foreach (var objective in state.Objectives)
        {
            ObjectivesContainer.AddChild(BuildRow(objective));
        }

        UpdateAddButton();
    }

    private void SetIssuers(List<CustomObjectiveIssuer> issuers)
    {
        var selected = IssuerOptions.SelectedId >= 0 && IssuerOptions.SelectedId < _issuerIds.Count
            ? _issuerIds[IssuerOptions.SelectedId]
            : SyndicateIssuerId;

        _issuerIds.Clear();
        IssuerOptions.Clear();

        foreach (var issuer in issuers)
        {
            IssuerOptions.AddItem(issuer.Name, _issuerIds.Count);
            if (issuer.Id == selected)
                IssuerOptions.SelectId(_issuerIds.Count);

            _issuerIds.Add(issuer.Id);
        }
    }

    private Control BuildRow(CustomObjectiveEntry entry)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 0, 0, 8) };

        box.AddChild(new Label { Text = entry.Title, StyleClasses = { "LabelKeyText" } });

        if (entry.Description.Length > 0)
            box.AddChild(new RichTextLabel { Text = entry.Description, HorizontalExpand = true });

        box.AddChild(new Label
        {
            Text = Loc.GetString("custom-objectives-row-issuer", ("issuer", entry.Issuer)),
            StyleClasses = { "LabelSmall" },
        });

        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        AddStatusButton(buttons, entry, CustomObjectiveStatus.Failed, "custom-objectives-status-failed");
        AddStatusButton(buttons, entry, CustomObjectiveStatus.Partial, "custom-objectives-status-partial");
        AddStatusButton(buttons, entry, CustomObjectiveStatus.Completed, "custom-objectives-status-completed");

        var remove = new ConfirmButton
        {
            Text = Loc.GetString("custom-objectives-remove"),
            ConfirmationText = Loc.GetString("custom-objectives-remove-confirm"),
            HorizontalExpand = true,
        };
        remove.OnPressed += _ => OnRemove?.Invoke(entry.Objective);
        buttons.AddChild(remove);

        box.AddChild(buttons);
        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" }, MinSize = new Vector2(0, 1) });
        return box;
    }

    private void AddStatusButton(BoxContainer parent, CustomObjectiveEntry entry, CustomObjectiveStatus status, string locId)
    {
        var button = new Button
        {
            Text = Loc.GetString(locId),
            Disabled = entry.Status == status,
            HorizontalExpand = true,
        };
        button.OnPressed += _ => OnSetStatus?.Invoke(entry.Objective, status);
        parent.AddChild(button);
    }

    private string GetDescription()
    {
        return Rope.Collapse(DescriptionEdit.TextRope);
    }

    private void UpdateAddButton()
    {
        var descriptionLength = DescriptionEdit.TextLength;
        DescriptionLimitLabel.Text = $"{descriptionLength}/{CustomObjectiveLimits.MaxDescriptionLength}";

        AddButton.Disabled = NoMindLabel.Visible ||
                             string.IsNullOrWhiteSpace(TitleEdit.Text) ||
                             descriptionLength > CustomObjectiveLimits.MaxDescriptionLength ||
                             IssuerOptions.SelectedId < 0;
    }

    private void Add()
    {
        if (IssuerOptions.SelectedId < 0 || IssuerOptions.SelectedId >= _issuerIds.Count)
            return;

        OnAdd?.Invoke(TitleEdit.Text, GetDescription(), _issuerIds[IssuerOptions.SelectedId]);

        TitleEdit.Text = string.Empty;
        DescriptionEdit.TextRope = new Rope.Leaf(string.Empty);
        UpdateAddButton();
    }
}
