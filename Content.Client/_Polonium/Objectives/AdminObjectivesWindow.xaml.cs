using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Polonium.Objectives;
using Content.Shared.Objectives.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Polonium.Objectives;

[GenerateTypedNameReferences]
public sealed partial class AdminObjectivesWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private static readonly ProtoId<ObjectiveIssuerPrototype> DefaultIssuer = "TheSyndicate";

    private List<AdminStandardObjective> _standardObjectives = new();
    private readonly List<string?> _filterIssuerIds = new();
    private readonly List<string> _issuerIds = new();
    private string? _selectedPrototype;
    private bool _hasMind;

    public event Action<string>? OnAddStandard;
    public event Action<string, string, string>? OnAddCustom;
    public event Action<NetEntity, CustomObjectiveStatus>? OnSetStatus;
    public event Action<NetEntity>? OnRemove;

    public AdminObjectivesWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DescriptionEdit.Placeholder = new Rope.Leaf(Loc.GetString("admin-objectives-description-placeholder"));

        SearchEdit.OnTextChanged += _ => FillPrototypeList();
        IssuerFilter.OnItemSelected += args =>
        {
            IssuerFilter.SelectId(args.Id);
            FillPrototypeList();
        };
        PrototypeList.OnItemSelected += args => SelectPrototype((string?) PrototypeList[args.ItemIndex].Metadata);
        PrototypeList.OnItemDeselected += _ => SelectPrototype(null);
        AddStandardButton.OnPressed += _ => AddStandard();

        TitleEdit.IsValid = text => text.Length <= CustomObjectives.MaxTitleLength;
        TitleEdit.OnTextChanged += _ => UpdateButtons();
        DescriptionEdit.OnTextChanged += _ => UpdateButtons();
        IssuerOptions.OnItemSelected += args => IssuerOptions.SelectId(args.Id);
        AddCustomButton.OnPressed += _ => AddCustom();

        LoadIssuers();
        UpdateButtons();
    }

    public void SetState(AdminObjectivesEuiState state)
    {
        _hasMind = state.HasMind;
        PlayerLabel.Text = Loc.GetString("admin-objectives-player", ("player", state.PlayerName));
        NoMindLabel.Visible = !state.HasMind;
        EmptyLabel.Visible = state.HasMind && state.Objectives.Count == 0;

        ObjectivesContainer.RemoveAllChildren();
        foreach (var objective in state.Objectives)
        {
            ObjectivesContainer.AddChild(BuildRow(objective));
        }

        if (!state.StandardObjectives.SequenceEqual(_standardObjectives))
        {
            _standardObjectives = state.StandardObjectives;
            LoadIssuerFilter();
            FillPrototypeList();
        }

        UpdateButtons();
    }

    public void ShowAddStandardFailed(string prototype)
    {
        var name = _standardObjectives.FirstOrDefault(o => o.Id == prototype).Name ?? prototype;
        StandardErrorLabel.SetMessage(
            FormattedMessage.FromUnformatted(Loc.GetString("admin-objectives-add-failed", ("objective", name))),
            Color.Red);
        StandardErrorScroll.Visible = true;
    }

    private string GetIssuerName(string id)
    {
        return _prototypes.TryIndex<ObjectiveIssuerPrototype>(id, out var issuer)
            ? FormattedMessage.RemoveMarkupPermissive(issuer.LocalizedName)
            : id;
    }

    private void LoadIssuers()
    {
        var issuers = _prototypes.EnumeratePrototypes<ObjectiveIssuerPrototype>()
            .Select(p => (p.ID, Name: GetIssuerName(p.ID)))
            .OrderBy(p => p.Name, StringComparer.CurrentCulture);

        foreach (var (id, name) in issuers)
        {
            IssuerOptions.AddItem(name, _issuerIds.Count);
            if (id == DefaultIssuer)
                IssuerOptions.SelectId(_issuerIds.Count);

            _issuerIds.Add(id);
        }
    }

    private void LoadIssuerFilter()
    {
        var selected = IssuerFilter.SelectedId > 0 && IssuerFilter.SelectedId < _filterIssuerIds.Count
            ? _filterIssuerIds[IssuerFilter.SelectedId]
            : null;

        _filterIssuerIds.Clear();
        IssuerFilter.Clear();

        IssuerFilter.AddItem(Loc.GetString("admin-objectives-filter-all"), 0);
        _filterIssuerIds.Add(null);

        var issuers = _standardObjectives
            .Select(o => o.Issuer)
            .Distinct()
            .Select(id => (Id: id, Name: GetIssuerName(id)))
            .OrderBy(p => p.Name, StringComparer.CurrentCulture);

        foreach (var (id, name) in issuers)
        {
            IssuerFilter.AddItem(name, _filterIssuerIds.Count);
            _filterIssuerIds.Add(id);
        }

        IssuerFilter.SelectId(Math.Max(0, _filterIssuerIds.IndexOf(selected)));
    }

    private void FillPrototypeList()
    {
        var search = SearchEdit.Text.Trim();
        var issuer = IssuerFilter.SelectedId >= 0 && IssuerFilter.SelectedId < _filterIssuerIds.Count
            ? _filterIssuerIds[IssuerFilter.SelectedId]
            : null;
        var selectedVisible = false;

        PrototypeList.Clear();
        foreach (var objective in _standardObjectives)
        {
            if (issuer != null && objective.Issuer != issuer)
                continue;

            if (search.Length > 0 &&
                !objective.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase) &&
                !objective.Id.Contains(search, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var item = PrototypeList.AddItem(objective.Name, metadata: objective.Id);
            item.TooltipText = $"{objective.Name}\n{GetIssuerName(objective.Issuer)}\n{objective.Id}";

            if (objective.Id != _selectedPrototype)
                continue;

            item.Selected = true;
            selectedVisible = true;
        }

        if (!selectedVisible)
            SelectPrototype(null);
    }

    private void SelectPrototype(string? prototype)
    {
        _selectedPrototype = prototype;
        StandardErrorScroll.Visible = false;
        UpdateButtons();
    }

    private Control BuildRow(AdminObjectiveEntry entry)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 0, 0, 8) };

        box.AddChild(new Label { Text = entry.Title, StyleClasses = { "LabelKeyText" } });

        if (entry.Description.Length > 0)
        {
            var description = new RichTextLabel { HorizontalExpand = true };
            description.SetMessage(FormattedMessage.FromUnformatted(entry.Description));
            box.AddChild(description);
        }

        box.AddChild(new RichTextLabel
        {
            Text = Loc.GetString("admin-objectives-row-issuer", ("issuer", entry.Issuer)),
            StyleClasses = { "LabelSmall" },
        });

        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };

        if (entry.CustomStatus is { } status)
        {
            AddStatusButton(buttons, entry.Objective, status, CustomObjectiveStatus.Failed, "admin-objectives-status-failed");
            AddStatusButton(buttons, entry.Objective, status, CustomObjectiveStatus.Partial, "admin-objectives-status-partial");
            AddStatusButton(buttons, entry.Objective, status, CustomObjectiveStatus.Completed, "admin-objectives-status-completed");
        }
        else
        {
            buttons.AddChild(new Label
            {
                Text = entry.Progress is { } progress
                    ? Loc.GetString("admin-objectives-progress", ("progress", (int) MathF.Round(progress * 100)))
                    : Loc.GetString("admin-objectives-progress-unknown"),
                HorizontalExpand = true,
            });
        }

        var remove = new ConfirmButton
        {
            Text = Loc.GetString("admin-objectives-remove"),
            ConfirmationText = Loc.GetString("admin-objectives-remove-confirm"),
            HorizontalExpand = entry.CustomStatus != null,
        };
        remove.OnPressed += _ => OnRemove?.Invoke(entry.Objective);
        buttons.AddChild(remove);

        box.AddChild(buttons);
        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" }, MinSize = new Vector2(0, 1) });
        return box;
    }

    private void AddStatusButton(
        BoxContainer parent,
        NetEntity objective,
        CustomObjectiveStatus current,
        CustomObjectiveStatus status,
        string locId)
    {
        var button = new Button
        {
            Text = Loc.GetString(locId),
            Disabled = current == status,
            HorizontalExpand = true,
        };
        button.OnPressed += _ => OnSetStatus?.Invoke(objective, status);
        parent.AddChild(button);
    }

    private void UpdateButtons()
    {
        var descriptionLength = DescriptionEdit.TextLength;
        DescriptionLimitLabel.Text = $"{descriptionLength}/{CustomObjectives.MaxDescriptionLength}";

        AddStandardButton.Disabled = !_hasMind || _selectedPrototype == null;
        AddCustomButton.Disabled = !_hasMind ||
                                   string.IsNullOrWhiteSpace(TitleEdit.Text) ||
                                   descriptionLength > CustomObjectives.MaxDescriptionLength ||
                                   IssuerOptions.SelectedId < 0;
    }

    private void AddStandard()
    {
        if (_selectedPrototype == null)
            return;

        StandardErrorScroll.Visible = false;
        OnAddStandard?.Invoke(_selectedPrototype);
    }

    private void AddCustom()
    {
        if (IssuerOptions.SelectedId < 0 || IssuerOptions.SelectedId >= _issuerIds.Count)
            return;

        OnAddCustom?.Invoke(TitleEdit.Text, Rope.Collapse(DescriptionEdit.TextRope), _issuerIds[IssuerOptions.SelectedId]);

        TitleEdit.Text = string.Empty;
        DescriptionEdit.TextRope = new Rope.Leaf(string.Empty);
        UpdateButtons();
    }
}
