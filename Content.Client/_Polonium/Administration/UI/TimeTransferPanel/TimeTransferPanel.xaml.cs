using System.Linq;
using Content.Shared._Polonium.Administration;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Polonium.Administration.UI.TimeTransferPanel;

[GenerateTypedNameReferences]
public sealed partial class TimeTransferPanel : DefaultWindow
{
    private static readonly TimeSpan SetConfirmTime = TimeSpan.FromSeconds(3);

    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    public event Action<string, List<TimeTransferData>, bool>? OnTransferMessageSend;

    private TimeSpan? _setButtonResetOn;

    public TimeTransferPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AddTimeButton.OnButtonUp += _ => TimeTransfer(false);
        SetTimeButton.OnButtonUp += OnSetTimeButtonPressed;
        GroupCheckbox.OnPressed += _ => UpdateGroup();
        JobSearch.OnTextChanged += _ => UpdateSearch();

        PopulateJobs();
        UpdateGroup();
        UpdateWarning(" ", Color.LightGreen);
    }

    private void PopulateJobs()
    {
        var spriteSystem = _entityManager.System<SpriteSystem>();
        var jobs = _prototypeManager.EnumeratePrototypes<JobPrototype>()
            .OrderBy(job => job.LocalizedName);

        foreach (var job in jobs)
        {
            JobContainer.AddChild(new TimeTransferEntry(job, spriteSystem, _prototypeManager));
        }
    }

    public void UpdateFlag(bool hasFlag)
    {
        AddTimeButton.Visible = hasFlag;
        SetTimeButton.Visible = hasFlag;

        if (!hasFlag)
            UpdateWarning(Loc.GetString("time-transfer-panel-warning-no-perms"), Color.DarkRed);
        else
            UpdateWarning(" ", Color.LightGreen);
    }

    public void UpdateWarning(string text, Color color)
    {
        WarningLabel.FontColorOverride = color;
        WarningLabel.Text = text;
    }

    private IEnumerable<TimeTransferEntry> Entries()
    {
        return JobContainer.Children.OfType<TimeTransferEntry>();
    }

    private void TimeTransfer(bool overwrite)
    {
        var player = PlayerLine.Text.Trim();
        if (player.Length == 0)
        {
            UpdateWarning(Loc.GetString("time-transfer-panel-warning-no-player"), Color.DarkRed);
            return;
        }

        var dataList = new List<TimeTransferData>();

        if (GroupCheckbox.Pressed)
        {
            var groupTime = GroupTimeLine.Text.Trim();
            if (groupTime.Length == 0)
            {
                UpdateWarning(Loc.GetString("time-transfer-panel-warning-group-no-time"), Color.DarkRed);
                return;
            }

            dataList.AddRange(Entries()
                .Where(entry => entry.InGroup())
                .Select(entry => new TimeTransferData(entry.PlaytimeTracker, groupTime)));
        }
        else
        {
            foreach (var entry in Entries())
            {
                var timeString = entry.GetJobTimeString().Trim();
                if (timeString.Length == 0)
                    continue;

                dataList.Add(new TimeTransferData(entry.PlaytimeTracker, timeString));
            }
        }

        if (dataList.Count == 0)
        {
            UpdateWarning(Loc.GetString("time-transfer-panel-warning-no-job"), Color.DarkRed);
            return;
        }

        OnTransferMessageSend?.Invoke(player, dataList, overwrite);
        UpdateWarning(Loc.GetString("time-transfer-panel-warning-transfer-process"), Color.Gold);
    }

    private void UpdateGroup()
    {
        GroupTimeLine.Visible = GroupCheckbox.Pressed;

        foreach (var entry in Entries())
        {
            entry.UpdateGroupVisibility(GroupCheckbox.Pressed);
        }
    }

    private void UpdateSearch()
    {
        foreach (var entry in Entries())
        {
            entry.Visible = entry.JobName.Contains(JobSearch.Text, StringComparison.OrdinalIgnoreCase);
        }
    }

    private void OnSetTimeButtonPressed(BaseButton.ButtonEventArgs args)
    {
        if (_setButtonResetOn is null)
        {
            _setButtonResetOn = _gameTiming.CurTime + SetConfirmTime;
            SetTimeButton.ModulateSelfOverride = Color.DarkRed;
            SetTimeButton.Text = Loc.GetString("time-transfer-panel-set-time-confirm");
            return;
        }

        TimeTransfer(true);
        ResetSetButton();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_setButtonResetOn != null && _gameTiming.CurTime > _setButtonResetOn)
            ResetSetButton();
    }

    private void ResetSetButton()
    {
        _setButtonResetOn = null;
        SetTimeButton.ModulateSelfOverride = null;
        SetTimeButton.Text = Loc.GetString("time-transfer-panel-set-time");
    }
}
