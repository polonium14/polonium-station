using Content.Shared._Polonium.DiscordLinking;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Polonium.DiscordLinking;

/// <summary>
/// Shows the Discord link of the local player and lets them link their account.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class DiscordLinkPanel : BoxContainer
{
    private readonly DiscordLinkSystem _system;
    private readonly IClipboardManager _clipboard;

    // The last page given by the server. Kept after a check, the player may still need it.
    private string? _url;

    public DiscordLinkPanel(DiscordLinkSystem system, IClipboardManager clipboard)
    {
        RobustXamlLoader.Load(this);

        _system = system;
        _clipboard = clipboard;

        LinkButton.OnPressed += _ => _system.RequestStart();
        CheckButton.OnPressed += _ => _system.RequestStatus();
        CopyLinkButton.OnPressed += _ =>
        {
            if (_url != null)
                _clipboard.SetText(_url);
        };
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system.StateChanged += Show;

        if (_system.State is { } state)
            Show(state);
        else
            SetStatus(Loc.GetString("discord-link-status-checking"));

        // Also when linked: an admin may have unlinked the account in the meantime.
        _system.RequestStatus();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _system.StateChanged -= Show;
    }

    private void Show(DiscordLinkStateEvent state)
    {
        var linked = state.Status == DiscordLinkStatus.Linked;
        if (linked)
            _url = null;
        else if (state is { Status: DiscordLinkStatus.Started, Url: { } url })
            _url = url;

        SetStatus(state.Status switch
        {
            DiscordLinkStatus.Linked when state.DiscordName is { } name =>
                Loc.GetString("discord-link-status-linked", ("name", name)),
            DiscordLinkStatus.Linked => Loc.GetString("discord-link-status-linked-unknown"),
            DiscordLinkStatus.Started => Loc.GetString("discord-link-status-started"),
            DiscordLinkStatus.NotLoggedIn => Loc.GetString("discord-link-status-not-logged-in"),
            DiscordLinkStatus.Unavailable => Loc.GetString("discord-link-status-unavailable"),
            DiscordLinkStatus.Cooldown => Loc.GetString("discord-link-status-cooldown"),
            _ => Loc.GetString("discord-link-status-not-linked"),
        });

        // A linked account needs no buttons, and a guest account can't be linked at all.
        var canLink = !linked && state.Status != DiscordLinkStatus.NotLoggedIn;
        LinkButton.Visible = canLink;
        CheckButton.Visible = canLink && _url != null;
        UrlRow.Visible = canLink && _url != null;
        UrlEdit.Text = _url ?? string.Empty;
    }

    private void SetStatus(string text)
    {
        // The Discord name comes from the user, so it must not be read as markup.
        StatusLabel.SetMessage(FormattedMessage.FromUnformatted(text));
    }
}
