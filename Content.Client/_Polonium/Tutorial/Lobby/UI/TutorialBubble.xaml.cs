using Content.Client.Resources;
using Robust.Shared.Configuration;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using System.Numerics;

namespace Content.Client._Polonium.Tutorial.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class TutorialBubble : Control
{
    public ClickBehaviour ClickAction { get; set; } = ClickBehaviour.CloseBubble;
    public Tippy TippyVariant { get; set; } = Tippy.ClownRegular;
    public bool FullSize { get; set; }

    /// <summary>Size multiplier to use instead of the saved one, for the live preview.</summary>
    public float? ScaleMultiplier { get; set; }
    public event Action? OnBubbleClosed;
    public BoxContainer ContentContainer => Content;
    public BoxContainer ButtonsContainer => Buttons;
    public RichTextLabel AnyKeyLabel => AnyKeyText;

    [Dependency] private IUserInterfaceManager _ui = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IResourceCache _resCache = default!;
    [Dependency] private IConfigurationManager _cfg = default!;

    private readonly TutorialUIController _tutorialUi;

    private const int BaseFontSize = 12;
    private const int MinFontSize = 8;

    private bool _scaled;
    private float _scale = 1f;

    public TutorialBubble()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _tutorialUi = _ui.GetUIController<TutorialUIController>();

        ApplyComicStyle();
        MouseFilter = MouseFilterMode.Stop;
        AnyKeyText.Modulate = Color.DarkGray;
    }

    public void ApplyFunctionalStyle()
    {
        OuterLayer.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#0E1A1FEE"),
            BorderColor = Color.FromHex("#65B8E2"),
            BorderThickness = new Thickness(2),
            ContentMarginLeftOverride = 18f,
            ContentMarginTopOverride = 10f,
            ContentMarginRightOverride = 18f,
            ContentMarginBottomOverride = 10f,
        };

        MaxWidth = 420;
        ModulateSelfOverride = null;
        TippyVariant = Tippy.None;
        AnyKeyText.Modulate = Color.FromHex("#8FB8CC");
        RecolorLabels(Color.White);
    }

    private void ApplyComicStyle()
    {
        var boxTexture = _resCache.GetTexture("/Textures/_Polonium/Interface/Nano/intro_bubble_outer.png");
        OuterLayer.PanelOverride = new StyleBoxTexture
        {
            Texture = boxTexture,
            ContentMarginLeftOverride = 20f,
            ContentMarginTopOverride = 20f,
            ContentMarginRightOverride = 20f,
            ContentMarginBottomOverride = 20f,
            PatchMarginLeft = 12f,
            PatchMarginTop = 12f,
            PatchMarginRight = 12f,
            PatchMarginBottom = 12f,
        };

        ModulateSelfOverride = Color.Transparent;
        RecolorLabels(Color.Black);
    }

    /// <summary>
    /// Default buttons are pale grey and vanish against the light comic bubble, so give the
    /// tutorial its own darker chip with the same blue the rest of the flow uses.
    /// </summary>
    public static Button MakeButton(string text, bool primary = true, bool compact = false)
    {
        var fill = compact ? Color.FromHex("#D0D0D0") : primary ? Color.FromHex("#2C4F63") : Color.FromHex("#4A4A4A");
        var hover = compact ? Color.FromHex("#E4E4E4") : primary ? Color.FromHex("#3A6884") : Color.FromHex("#5C5C5C");

        var button = new Button
        {
            Text = text,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, compact ? 8 : 6, 0, 0),
            MinWidth = compact ? 0 : 190,
        };

        button.AddStyleClass("ButtonSquare");
        if (compact)
        {
            button.AddStyleClass("ButtonSmall");
            button.ModulateSelfOverride = Color.White;
        }

        var style = new StyleBoxFlat
        {
            BackgroundColor = fill,
            BorderColor = compact ? Color.FromHex("#B8B8B8") : Color.FromHex("#65B8E2"),
            BorderThickness = new Thickness(compact ? 1 : 2),
            ContentMarginLeftOverride = compact ? 8f : 14f,
            ContentMarginRightOverride = compact ? 8f : 14f,
            ContentMarginTopOverride = compact ? 2f : 6f,
            ContentMarginBottomOverride = compact ? 2f : 6f,
        };

        button.StyleBoxOverride = style;
        button.Label.Modulate = compact ? Color.FromHex("#333333") : Color.White;

        button.OnMouseEntered += _ => style.BackgroundColor = hover;
        button.OnMouseExited += _ => style.BackgroundColor = fill;

        return button;
    }

    private void RecolorLabels(Color color)
    {
        foreach (var child in BubbleMain.Children)
        {
            if (child is RichTextLabel label)
                label.Modulate = color;
        }
    }

    public TutorialBubble(string text) : this()
    {
        var label = new RichTextLabel
        {
            Text = text,
            Modulate = Color.Black,
        };
        BubbleMain.AddChild(label);
    }

    public TutorialBubble(params string[] texts) : this()
    {
        foreach (var text in texts)
        {
            var label = new RichTextLabel
            {
                Text = text,
                Modulate = Color.Black,
                Margin = new Thickness(0f, 5f),
            };

            BubbleMain.AddChild(label);
        }
    }

    private void CloseBubble()
    {
        OnBubbleClosed?.Invoke();
        Orphan();
    }

    public enum ClickBehaviour
    {
        Ignore,
        CloseBubble,
        CloseOverlay,
        FinishTutorial,
    }

    public enum Tippy
    {
        None,
        ClownRegular,
        ClownPointing,
        WavingHand,
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        AnyKeyText.Visible = ClickAction != ClickBehaviour.Ignore;

        var overlay = _tutorialUi.ActiveOverlay;
        AnyKeyText.Text = overlay is not null && overlay.IsSelfClosingOnClick
            ? _loc.GetString("intro-click-any-to-continue-label")
            : _loc.GetString("intro-click-to-continue-label");

        if (!_scaled)
        {
            _scaled = true;
            // full size bubbles are the big centred ones, they already fit anywhere
            _scale = FullSize
                ? 1f
                : TutorialBubbleScale.Effective(_ui, ScaleMultiplier ?? TutorialBubbleScale.Multiplier(_cfg));

            if (MathF.Abs(_scale - 1f) > 0.01f)
                ApplyScale();
        }

        if (TippyVariant == Tippy.None)
            return;

        var tippyTexture = TippyVariant switch
        {
            Tippy.ClownRegular => _resCache.GetTexture("/Textures/_Polonium/Interface/Misc/intro_markers/clown.png"),
            Tippy.ClownPointing => _resCache.GetTexture("/Textures/_Polonium/Interface/Misc/intro_markers/clown_tip.png"),
            Tippy.WavingHand => _resCache.GetTexture("/Textures/_Polonium/Interface/Misc/intro_markers/siema.png"),
            _ => throw new ArgumentOutOfRangeException(),
        };

        var tippyScale = _scale;
        var tippyIcon = new TextureRect
        {
            Texture = tippyTexture,
            HorizontalAlignment = HAlignment.Right,
            VerticalAlignment = VAlignment.Bottom,
            Margin = new Thickness(0, 0, -80 * tippyScale, -32 * tippyScale),
            SetSize = new Vector2(96 * tippyScale, 96 * tippyScale),
            Stretch = TextureRect.StretchMode.Scale,
            MouseFilter = MouseFilterMode.Ignore,
        };

        OuterLayer.AddChild(tippyIcon);
    }

    private void ApplyScale()
    {
        MaxWidth *= _scale;
        if (BubbleMain.MaxWidth < float.PositiveInfinity)
            BubbleMain.MaxWidth *= _scale;

        switch (OuterLayer.PanelOverride)
        {
            case StyleBoxTexture box:
                box.TextureScale = new Vector2(_scale, _scale);
                box.ContentMarginLeftOverride *= _scale;
                box.ContentMarginTopOverride *= _scale;
                box.ContentMarginRightOverride *= _scale;
                box.ContentMarginBottomOverride *= _scale;
                break;
            case StyleBoxFlat flat:
                ScaleFlat(flat);
                break;
        }

        Content.Margin = ScaleThickness(Content.Margin);
        Buttons.Margin = ScaleThickness(Buttons.Margin);
        Content.SeparationOverride = ScaleSep(Content.SeparationOverride);
        Buttons.SeparationOverride = ScaleSep(Buttons.SeparationOverride);

        var fontSize = Math.Max(MinFontSize, (int) MathF.Round(BaseFontSize * _scale));
        var font = _resCache.GetFont("/Fonts/Atkinson/AtkinsonHyperlegibleNext-Regular.ttf", fontSize);
        ScaleControl(this, font, fontSize);
    }

    private void ScaleControl(Control control, Font font, int fontSize)
    {
        switch (control)
        {
            case RichTextLabel rich:
                WrapFont(rich, fontSize);
                rich.Margin = ScaleThickness(rich.Margin);
                break;
            case Label label when control.Parent is not Button btn || !btn.HasStyleClass("ButtonSmall"):
                label.FontOverride = font;
                break;
            case Button button:
                if (button.MinWidth > 0)
                    button.MinWidth *= _scale;
                button.Margin = ScaleThickness(button.Margin);
                if (button.StyleBoxOverride is StyleBoxFlat flat)
                    ScaleFlat(flat);
                break;
            case TextureRect tex:
                if (tex.Texture is { } texture)
                {
                    var size = tex.SetSize;
                    if (size == default)
                        size = new Vector2(texture.Width, texture.Height);
                    tex.SetSize = size * _scale;
                }

                tex.Margin = ScaleThickness(tex.Margin);
                break;
        }

        foreach (var child in control.Children)
            ScaleControl(child, font, fontSize);
    }

    private static void WrapFont(RichTextLabel label, int fontSize)
    {
        var text = label.Text;
        if (string.IsNullOrEmpty(text) || text.StartsWith("[font size=", StringComparison.Ordinal))
            return;

        label.Text = $"[font size={fontSize}]{text}[/font]";
    }

    private void ScaleFlat(StyleBoxFlat flat)
    {
        flat.ContentMarginLeftOverride *= _scale;
        flat.ContentMarginRightOverride *= _scale;
        flat.ContentMarginTopOverride *= _scale;
        flat.ContentMarginBottomOverride *= _scale;
    }

    private Thickness ScaleThickness(Thickness thickness)
    {
        return new Thickness(
            thickness.Left * _scale,
            thickness.Top * _scale,
            thickness.Right * _scale,
            thickness.Bottom * _scale);
    }

    private int ScaleSep(int? separation)
    {
        return (int) MathF.Round((separation ?? 10) * _scale);
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        switch (ClickAction)
        {
            case ClickBehaviour.Ignore:
                break;
            case ClickBehaviour.CloseBubble:
                CloseBubble();
                break;
            case ClickBehaviour.CloseOverlay:
                _tutorialUi.RequestClose(false);
                break;
            case ClickBehaviour.FinishTutorial:
                _tutorialUi.RequestClose(true);
                break;
            default:
                throw new ArgumentOutOfRangeException();
        }

        args.Handle();
    }
}
